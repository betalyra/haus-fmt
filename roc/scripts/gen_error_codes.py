#!/usr/bin/env python3
"""Update the generated part of roc/package/ErrorCode.roc from spec/errors.haus.

The catalogue of error codes (spec §17) is the single source: this writes a
constant per code (`ErrorCode.payload_newline == "payload-newline"`), `all`,
`hint` (the catalogue's fix) and `category` between the module's
"generated" markers, and leaves the rest of the module alone. A test in
ConformanceTest.roc (gen_conformance.py) reads the catalogue with the Roc
parser and fails if this part is out of date. Re-run after changing
spec/errors.haus:

    python3 roc/scripts/gen_error_codes.py
"""
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "spec" / "errors.haus"
OUT = ROOT / "roc" / "package" / "ErrorCode.roc"
BEGIN = "# ── generated by roc/scripts/gen_error_codes.py from spec/errors.haus: don't edit ──"
END = "# ── end of the generated part ──"

STRING = r'"((?:[^"\\\n]|\\.)*)"'
ESCAPES = {'"': '"', "\\": "\\", "n": "\n", "r": "\r", "t": "\t"}


def unescape(s: str) -> str:
    """The text of a haus basic string's content."""
    return re.sub(
        r"\\(u\{([0-9A-Fa-f]{1,6})\}|.)",
        lambda m: chr(int(m.group(2), 16)) if m.group(2) else ESCAPES[m.group(1)],
        s,
    )


def roc_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def kebab(tag: str) -> str:
    """`SchemaFiles` → `schema-files`: the category's id, as in the TypeScript table."""
    return re.sub(r"(?<!^)(?=[A-Z])", "-", tag).lower()


def entries() -> list[dict[str, str]]:
    text = SOURCE.read_text(encoding="utf-8")
    out = []
    # Each entry starts a line with `Code {`; its fields are on lines of their own.
    for block in re.split(r"^Code \{", text, flags=re.M)[1:]:
        field = lambda key, value: re.search(rf"^\s*{key}: {value},?$", block, re.M)
        code, category, means, fix = field("code", STRING), field("category", r"([A-Z]\w*)"), field("means", STRING), field("fix", STRING)
        if not (code and category and means and fix):
            raise SystemExit(f"spec/errors.haus: can't read the entry {block[:60]!r}")
        out.append({"code": unescape(code[1]), "category": kebab(category[1]), "means": unescape(means[1]), "fix": unescape(fix[1])})
    return out


codes = entries()
lines = [BEGIN, ""]
for e in codes:
    name = e["code"].replace("-", "_")
    lines += [f"## `{e['code']}` ({e['category']}): {e['means']}", f"{name} : Str", f"{name} = {roc_str(e['code'])}", ""]
lines += [
    "## Every code, in the catalogue's order.",
    "all : List(Str)",
    "all = [" + ", ".join(roc_str(e["code"]) for e in codes) + "]",
    "",
    "## The catalogue's fix for a code, which errors report as their hint:",
    "## `ErrorCode.hint(\"missing-comma\")` is \"Add a comma between the two values.\".",
    "## Empty for a text that isn't a code.",
    "hint : Str -> Str",
    "hint = |code| match code {",
    *(f"\t{roc_str(e['code'])} => {roc_str(e['fix'])}" for e in codes),
    '\t_ => ""',
    "}",
    "",
    "## The catalogue's category of a code: `syntax`, `limits`, `streams`,",
    "## `schema-files`, `imports`, `decoding`, `json` or `hints`. Empty for a",
    "## text that isn't a code.",
    "category : Str -> Str",
    "category = |code| match code {",
    *(f"\t{roc_str(e['code'])} => {roc_str(e['category'])}" for e in codes),
    '\t_ => ""',
    "}",
    "",
    END,
]
generated = "\n".join("\t" + l if l else "" for l in lines)

module = OUT.read_text(encoding="utf-8")
start, end = module.find("\t" + BEGIN), module.find("\t" + END)
if start < 0 or end < 0:
    raise SystemExit(f"{OUT.relative_to(ROOT)}: the markers of the generated part are missing")
OUT.write_text(module[:start] + generated + module[end + len(END) + 1 :], encoding="utf-8")
subprocess.run(["roc", "fmt", str(OUT)], check=True, capture_output=True)
print(f"wrote {OUT.relative_to(ROOT)}: {len(codes)} codes")
