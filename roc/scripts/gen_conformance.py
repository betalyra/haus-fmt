#!/usr/bin/env python3
"""Generate roc/package/ConformanceTest.roc from the shared test-suite.

Each fixture is embedded with `import "…" as name : List(U8)`, so `roc test`
runs the suite without a platform. A valid file's values must be those of its
NAME.jsonl (self-describing JSON, spec §16.2, one envelope per value), checked
in the form `Value.to_test_json` writes (the parser fuzzer's): the same,
with keys without the leading `_`. An invalid file must be rejected with the
error code of its NAME.error (spec §17), by the parser and by the stream
reader. The catalogue of codes, spec/errors.haus, is embedded too: the test
fails if roc/package/ErrorCode.roc is out of date (gen_error_codes.py).
Re-run after changing test-suite/.
"""
import json
import subprocess
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SUITE = ROOT / "test-suite"
OUT = ROOT / "roc" / "package" / "ConformanceTest.roc"


def test_json(v):
    """A self-describing JSON value (without the envelope) in the form of
    `Value.to_test_json`: `{"_num": "1"}` is `{"num": "1"}`."""
    if isinstance(v, list):
        return [test_json(x) for x in v]
    if isinstance(v, dict):
        if "_rec" in v:
            return {"rec": {k: test_json(x) for k, x in v["_rec"].items()}}
        return {k.removeprefix("_"): test_json(x) for k, x in v.items()}
    return v


def expected_values(path: Path) -> list:
    """The values of a valid file, from its NAME.jsonl."""
    lines = path.with_suffix(".jsonl").read_text(encoding="utf-8").splitlines()
    envelopes = [json.loads(l) for l in lines if l.strip()]
    assert all(set(e) == {"_haus", "_value"} and e["_haus"] == 1 for e in envelopes), path
    return [test_json(e["_value"]) for e in envelopes]


def ident(kind: str, name: str) -> str:
    return f"{kind}_{re.sub(r'[^a-z0-9]', '_', name.lower())}"


BIDI = re.compile("[\u202a-\u202e\u2066-\u2069\x7f-\x9f]")


def roc_str(s: str) -> str:
    s = s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$")
    # Roc (like haus) rejects raw bidi and control characters in source; write them as escapes.
    s = BIDI.sub(lambda m: f"\\u({ord(m.group()):04X})", s)
    return '"' + s + '"'


imports, tests = [], []
for path in sorted((SUITE / "valid").glob("*.haus")):
    name = ident("valid", path.stem)
    expected = expected_values(path)
    imports.append(f'import "../../test-suite/valid/{path.name}" as {name} : List(U8)')
    tests.append(f"# valid/{path.name}\nexpect ConformanceTest.run({name}) == {roc_str(json.dumps(expected, ensure_ascii=False, separators=(',', ':')))}")
    # The canonical form of each value, one per line (spec §12).
    imports.append(f'import "../../test-suite/valid/{path.stem}.canonical" as {name}_canonical : List(U8)')
    tests.append(f"# valid/{path.stem}.canonical\nexpect ConformanceTest.canonical({name}) == {name}_canonical")
    # `hashAll` of the values (spec §12), as hex and a line break.
    imports.append(f'import "../../test-suite/valid/{path.stem}.hash" as {name}_hash : List(U8)')
    tests.append(f"# valid/{path.stem}.hash\nexpect ConformanceTest.hash({name}) == {name}_hash")
    tests.append(f"# valid/{path.name}, streamed\nexpect ConformanceTest.streams({name})")
for path in sorted((SUITE / "invalid").glob("*.haus")):
    name = ident("invalid", path.stem)
    code = roc_str(path.with_suffix(".error").read_text(encoding="utf-8").strip())
    imports.append(f'import "../../test-suite/invalid/{path.name}" as {name} : List(U8)')
    tests.append(f"# invalid/{path.name}\nexpect ConformanceTest.rejects({name}, {code})")
    tests.append(f"# invalid/{path.name}, streamed\nexpect ConformanceTest.stream_rejects({name}, {code})")
# Error positions (test-suite/positions, spec §8) and equality and order
# (test-suite/equality, spec §2, §12): the cases files are embedded as they are
# and every case runs in one `expect`, which reports each failing case, so the
# files can change without regenerating this module.
imports.append('import "../../test-suite/positions/cases.haus" as positions_cases : Str')
tests.append("# positions/cases.haus\nexpect ConformanceTest.positions(positions_cases)")
imports.append('import "../../test-suite/equality/cases.haus" as equality_cases : Str')
tests.append("# equality/cases.haus\nexpect ConformanceTest.equality(equality_cases)")
imports.append('import "../../spec/errors.haus" as error_catalogue : Str')
tests.append("# spec/errors.haus: ErrorCode.roc is up to date (roc/scripts/gen_error_codes.py)\nexpect ConformanceTest.catalogue(error_catalogue)")

OUT.write_text(
    "# GENERATED by roc/scripts/gen_conformance.py from test-suite/. Do not edit.\n"
    "import Encode\n"
    "import ErrorCode\n"
    "import Streaming\n"
    "import Value\n"
    + "\n".join(imports)
    + """

ConformanceTest := [].{
    ## The parsed values in the suite's JSON form, or the error.
    run : List(U8) -> Str
    run = |bytes| match Value.parse_bytes(bytes) {
        Ok(values) => "[${Str.join_with(values.map(Value.to_test_json), ",")}]"
        Err({ reason, line, column, .. }) => "ERROR ${reason} at ${line.to_str()}:${column.to_str()}"
    }

    ## The canonical form of each value, one per line.
    canonical : List(U8) -> List(U8)
    canonical = |bytes| match Value.parse_bytes(bytes) {
        Ok(values) => Str.join_with(values.map(|v| "${Encode.canonical(v) ?? "(no canonical form)"}\\n"), "").to_utf8()
        Err(_) => []
    }

    ## Rejected, with the error code `code` (spec §17).
    rejects : List(U8), Str -> Bool
    rejects = |bytes, code| match Value.parse_bytes(bytes) {
        Ok(_) => False
        Err(e) if e.code == code => True
        Err(e) => {
            dbg (e.code, e.reason)
            False
        }
    }

    ## `hash_all` of the values, as the suite writes it: hex and a line break.
    hash : List(U8) -> List(U8)
    hash = |bytes| match Value.parse_bytes(bytes) {
        Ok(values) => {
            whole = Encode.hash_all(values) ?? ""
            if (whole != "") "${whole}\\n".to_utf8() else []
        }
        _ => []
    }

    ## The stream reader gives the same values as the whole-file parser, in
    ## chunks of any size.
    streams : List(U8) -> Bool
    streams = |bytes| {
        whole = run(bytes)
        [1, 2, 3, 4, 5, 6, 7, 8, 9, bytes.len()].all(|size| streamed_json(bytes, size) == whole)
    }

    ## The stream reader rejects the input in chunks of any size, with the
    ## error code `code`. After a byte order mark, its error positions are the
    ## whole-file parser's.
    stream_rejects : List(U8), Str -> Bool
    stream_rejects = |bytes, code| {
        with_bom = [0xEF, 0xBB, 0xBF].concat(bytes)
        sizes = [1, 5, bytes.len()]
        rejected = sizes.all(
            |size| match streamed(bytes, size) {
                Err(e) => e.code == code
                Ok(_) => False
            },
        )
        same_place = match Value.parse_bytes(with_bom) {
            Err(e) if e.code != ErrorCode.invalid_utf8 => sizes.all(
                |size| match streamed(with_bom, size) {
                    Err(s) => (s.line, s.column) == (e.line, e.column)
                    Ok(_) => False
                },
            )
            # The stream reader may find an error before the invalid UTF-8.
            Err(_) => True
            Ok(_) => False
        }
        rejected and same_place
    }

    ## Every case of positions/cases.haus (spec §8): parsing `text` whole fails
    ## with `code` at `line`:`column` (1-based, columns in code points).
    positions : Str -> Bool
    positions = |cases| all_cases(cases, position_case)

    ## Every case of equality/cases.haus (spec §2, §12): `Encode.equals` both
    ## ways is `equal`, and `Encode.compare(a, b)` is `order` (-1, 0, 1),
    ## `compare(b, a)` the opposite.
    equality : Str -> Bool
    equality = |cases| all_cases(cases, equality_case)

    ## The catalogue of error codes (spec/errors.haus, read with this parser)
    ## and ErrorCode.roc have the same codes, in the same order, with the same
    ## categories and fixes.
    catalogue : Str -> Bool
    catalogue = |text| match Value.parse_all(text) {
        Ok(entries) => {
            read = entries.map(
                |entry| match entry {
                    Tag("Code", [Rec(fields)]) => match (field(fields, "code"), field(fields, "category"), field(fields, "fix")) {
                        (Text(code), Tag(category, []), Text(fix)) => (code, category, fix)
                        _ => ("", "", "")
                    }
                    _ => ("", "", "")
                },
            )
            codes = read.map(|(code, _, _)| code)
            stale = read.keep_if(|(code, category, fix)| ErrorCode.hint(code) != fix or ErrorCode.category(code) != kebab(category))
            if codes == ErrorCode.all and stale.is_empty() {
                True
            } else {
                dbg stale.map(|(code, _, _)| code)
                False
            }
        }
        Err(_) => False
    }
}

## A field of a record, or an empty string.
field : List((Str, Value)), Str -> Value
field = |fields, key| match fields.find_first(|(k, _)| k == key) {
    Ok((_, v)) => v
    Err(_) => Text("")
}

## The cases of a cases file all pass (and there are some); each failing
## case is reported.
all_cases : Str, (List((Str, Value)) -> Try({}, Str)) -> Bool
all_cases = |text, run_case| match Value.parse_all(text) {
    Ok(cases) => {
        failures = cases.keep_oks(
            |c| match c {
                Rec(fields) => match run_case(fields) {
                    Ok({}) => Err({})
                    Err(reason) => Ok(reason)
                }
                _ => Ok("not a case: ${Value.to_test_json(c)}")
            },
        )
        if failures.is_empty() {
            !cases.is_empty()
        } else {
            dbg failures
            False
        }
    }
    Err(e) => {
        dbg e.reason
        False
    }
}

position_case : List((Str, Value)) -> Try({}, Str)
position_case = |fields| match (field(fields, "text"), field(fields, "code"), field(fields, "line"), field(fields, "column")) {
    (Text(text), Text(code), Num(line), Num(column)) => {
        want = "${code} ${line}:${column}"
        got = match Value.parse_all(text) {
            Ok(_) => "parsed"
            Err(e) => "${e.code} ${e.line.to_str()}:${e.column.to_str()}"
        }
        if (got == want) Ok({}) else Err("${Encode.canonical(Text(text)) ?? text}: ${got}, expected ${want}")
    }
    _ => Err("not a case")
}

equality_case : List((Str, Value)) -> Try({}, Str)
equality_case = |fields| {
    a = field(fields, "a")
    b = field(fields, "b")
    equal = match field(fields, "equal") {
        Tag("True", []) => True
        _ => False
    }
    order = match field(fields, "order") {
        Num("-1") => Before
        Num("0") => Same
        Num("1") => After
        _ => return Err("not a case")
    }
    opposite = match order {
        Before => After
        Same => Same
        After => Before
    }
    want = (Ok(equal), Ok(equal), Ok(order), Ok(opposite))
    got = (Encode.equals(a, b), Encode.equals(b, a), Encode.compare(a, b), Encode.compare(b, a))
    if got == want {
        Ok({})
    } else {
        Err("${form(a)} ${form(b)}: equals ${Str.inspect(got.0)}, ${Str.inspect(got.1)}; compare ${Str.inspect(got.2)}, ${Str.inspect(got.3)}; expected equal ${Str.inspect(equal)}, order ${Str.inspect(order)}")
    }
}

form : Value -> Str
form = |v| Encode.canonical(v) ?? "(no canonical form)"

## `SchemaFiles` → `schema-files`
kebab : Str -> Str
kebab = |tag| {
    var $out = []
    for c in tag.to_utf8() {
        $out =
            if c >= 'A' and c <= 'Z' {
                (if ($out.is_empty()) $out else $out.append('-')).append(c + 32)
            } else {
                $out.append(c)
            }
    }
    Str.from_utf8($out) ?? tag
}

## The values of `bytes`, pushed to the stream reader in chunks of `size` bytes.
streamed : List(U8), U64 -> Try(List(Value), Value.ParseError)
streamed = |bytes, size| {
    var $chunks = []
    var $i = 0
    while $i < bytes.len() {
        $chunks = $chunks.append(bytes.sublist({ start: $i, len: size }))
        $i = $i + size
    }
    Streaming.all($chunks)
}

streamed_json : List(U8), U64 -> Str
streamed_json = |bytes, size| match streamed(bytes, size) {
    Ok(values) => "[${Str.join_with(values.map(Value.to_test_json), ",")}]"
    Err({ reason, line, column, .. }) => "ERROR ${reason} at ${line.to_str()}:${column.to_str()}"
}

"""
    + "\n\n".join(tests)
    + "\n",
    encoding="utf-8",
)
subprocess.run(["roc", "fmt", str(OUT)], check=True, capture_output=True)
print(f"wrote {OUT.relative_to(ROOT)}: {len(tests)} tests")
