#!/usr/bin/env python3
"""Generate roc/package/ConformanceTest.roc from the shared test-suite.

Each fixture is embedded with `import "…" as name : List(U8)`, so `roc test`
runs the suite without a platform. Re-run after changing test-suite/.
"""
import json
import subprocess
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SUITE = ROOT / "test-suite"
OUT = ROOT / "roc" / "package" / "ConformanceTest.roc"


def ident(kind: str, name: str) -> str:
    return f"{kind}_{re.sub(r'[^a-z0-9]', '_', name.lower())}"


BIDI = re.compile("[\u202a-\u202e\u2066-\u2069\x7f-\x9f]")


def roc_str(s: str) -> str:
    s = s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$")
    # Roc (like haus) rejects raw bidi and control characters in source; write them as escapes.
    s = BIDI.sub(lambda m: f"\\u({ord(m.group()):04X})", s)
    return '"' + s + '"'


imports, tests = [], []
for path in sorted((SUITE / "valid").glob("*.haus")):
    name = ident("valid", path.stem)
    expected = json.loads(path.with_suffix(".json").read_text(encoding="utf-8"))
    imports.append(f'import "../../test-suite/valid/{path.name}" as {name} : List(U8)')
    tests.append(f"# valid/{path.name}\nexpect ConformanceTest.run({name}) == {roc_str(json.dumps(expected, ensure_ascii=False, separators=(',', ':')))}")
    # The canonical form of each value, one per line (spec §12).
    imports.append(f'import "../../test-suite/valid/{path.stem}.canonical" as {name}_canonical : List(U8)')
    tests.append(f"# valid/{path.stem}.canonical\nexpect ConformanceTest.canonical({name}) == {name}_canonical")
    # `hashAll` of the values (spec §12), as hex and a line break.
    imports.append(f'import "../../test-suite/valid/{path.stem}.hash" as {name}_hash : List(U8)')
    tests.append(f"# valid/{path.stem}.hash\nexpect ConformanceTest.hash({name}) == {name}_hash")
    tests.append(f"# valid/{path.name}, streamed\nexpect ConformanceTest.streams({name})")
for path in sorted((SUITE / "invalid").glob("*.haus")):
    name = ident("invalid", path.stem)
    imports.append(f'import "../../test-suite/invalid/{path.name}" as {name} : List(U8)')
    tests.append(f"# invalid/{path.name}\nexpect ConformanceTest.rejects({name})")
    tests.append(f"# invalid/{path.name}, streamed\nexpect ConformanceTest.stream_rejects({name})")

OUT.write_text(
    "# GENERATED by roc/scripts/gen_conformance.py from test-suite/. Do not edit.\n"
    "import Encode\n"
    "import Streaming\n"
    "import Value\n"
    + "\n".join(imports)
    + """

ConformanceTest := [].{
    ## The parsed values in the suite's JSON form, or the error.
    run : List(U8) -> Str
    run = |bytes| match Value.parse_bytes(bytes) {
        Ok(values) => "[${Str.join_with(values.map(Value.to_test_json), ",")}]"
        Err({ reason, line, column }) => "ERROR ${reason} at ${line.to_str()}:${column.to_str()}"
    }

    ## The canonical form of each value, one per line.
    canonical : List(U8) -> List(U8)
    canonical = |bytes| match Value.parse_bytes(bytes) {
        Ok(values) => Str.join_with(values.map(|v| "${Encode.canonical(v)}\\n"), "").to_utf8()
        Err(_) => []
    }

    rejects : List(U8) -> Bool
    rejects = |bytes| match Value.parse_bytes(bytes) {
        Ok(_) => False
        Err(_) => True
    }

    ## `hash_all` of the values, as the suite writes it: hex and a line break.
    ## The running hash of the values as they are streamed gives the same.
    hash : List(U8) -> List(U8)
    hash = |bytes| match (Value.parse_bytes(bytes), streamed(bytes, 3)) {
        (Ok(values), Ok(again)) => {
            whole = Encode.hash_all(values)
            running = again.fold(Encode.HashAll.empty, Encode.HashAll.add).digest()
            if (running == whole) "${whole}\\n".to_utf8() else []
        }
        _ => []
    }

    ## The stream reader gives the same values as the whole-file parser, in
    ## chunks of any size.
    streams : List(U8) -> Bool
    streams = |bytes| {
        whole = run(bytes)
        [1, 2, 3, 4, 5, 6, 7, 8, 9, bytes.len()].all(|size| streamed_json(bytes, size) == whole)
    }

    ## The stream reader rejects the input in chunks of any size. After a byte
    ## order mark, its error positions are the whole-file parser's.
    stream_rejects : List(U8) -> Bool
    stream_rejects = |bytes| {
        with_bom = [0xEF, 0xBB, 0xBF].concat(bytes)
        sizes = [1, 5, bytes.len()]
        rejected = sizes.all(|size| streamed(bytes, size).is_err())
        same_place = match Value.parse_bytes(with_bom) {
            Err(e) if e.reason != "invalid UTF-8" => sizes.all(
                |size| match streamed(with_bom, size) {
                    Err(s) => (s.line, s.column) == (e.line, e.column)
                    Ok(_) => False
                },
            )
            # The whole-file parser doesn't say where invalid UTF-8 is.
            Err(_) => True
            Ok(_) => False
        }
        rejected and same_place
    }
}

## The values of `bytes`, pushed to the stream reader in chunks of `size` bytes.
streamed : List(U8), U64 -> Try(List(Value), Value.ParseError)
streamed = |bytes, size| {
    var $chunks = []
    var $i = 0
    while $i < bytes.len() {
        $chunks = $chunks.append(bytes.sublist({ start: $i, len: size }))
        $i = $i + size
    }
    Streaming.all($chunks)
}

streamed_json : List(U8), U64 -> Str
streamed_json = |bytes, size| match streamed(bytes, size) {
    Ok(values) => "[${Str.join_with(values.map(Value.to_test_json), ",")}]"
    Err({ reason, line, column }) => "ERROR ${reason} at ${line.to_str()}:${column.to_str()}"
}

"""
    + "\n\n".join(tests)
    + "\n",
    encoding="utf-8",
)
subprocess.run(["roc", "fmt", str(OUT)], check=True, capture_output=True)
print(f"wrote {OUT.relative_to(ROOT)}: {len(tests)} tests")
