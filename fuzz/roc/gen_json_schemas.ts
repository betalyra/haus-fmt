/**
 * Generates the Roc package that the Roc runner of the JSON fuzzer
 * (json_runner.roc) uses: for each schema of test-suite/schema, fuzz/schema,
 * test-suite/json and fuzz/json, `haus-gen roc --json` writes the module NAME.roc (its
 * types, decoders, encoders and plain JSON readers and writers), and
 * JsonSchemas.roc dispatches on the schema and type names. Writes
 * fuzz/.build/roc-json/; run by fuzz/build.sh. Needs Rust (cargo).
 */
import { spawnSync } from "node:child_process"
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const root = new URL("../..", import.meta.url).pathname
const out = join(root, "fuzz/.build/roc-json")
const dirs = [join(root, "test-suite/schema"), join(root, "fuzz/schema"), join(root, "test-suite/json"), join(root, "fuzz/json")]

const pascal = (s: string) => s.split(/[^A-Za-z0-9]+/).filter(Boolean).map((w) => w[0]!.toUpperCase() + w.slice(1)).join("")

/** Like `snake` in rust/haus-build/src/roc.rs: `IntPair` → `int_pair`. */
function snake(s: string): string {
  let o = ""
  for (const [i, c] of [...s].entries()) {
    if (/[A-Z]/.test(c)) o += (i > 0 && !o.endsWith("_") ? "_" : "") + c.toLowerCase()
    else if (/[a-z0-9]/.test(c)) o += c
    else if (o && !o.endsWith("_")) o += "_"
  }
  return o
}

const roc = (s: string) => JSON.stringify(s).replace(/\$/g, "\\$")

mkdirSync(out, { recursive: true })
const schemas = dirs.flatMap((d) => readdirSync(d).filter((f) => f.endsWith(".schema.haus")).map((f) => join(d, f))).sort()
const modules: string[] = []
const writes: string[] = []
const reads: string[] = []
const codecs: string[] = []
for (const path of schemas) {
  const name = path.split("/").pop()!.replace(".schema.haus", "")
  const module = pascal(name)
  modules.push(module)
  const p = spawnSync("cargo", ["run", "-q", "--manifest-path", join(root, "rust/Cargo.toml"), "-p", "haus-fmt-build", "--bin", "haus-gen", "--", "roc", path, "--module", module, "--json", "--out", join(out, `${module}.roc`)], { encoding: "utf8" })
  if (p.status !== 0) throw new Error(`haus-gen roc ${path} failed: ${p.stderr}`)
  // The non-generic definitions are the types a case can name.
  const types = [...readFileSync(path, "utf8").matchAll(/^type\s+([A-Z][A-Za-z0-9_]*)\s*=/gm)].map((m) => m[1]!)
  const s = snake(name)
  writes.push(`\t\t${roc(name)} => write_${s}(ty, v)\n`)
  reads.push(`\t\t${roc(name)} => read_${s}(ty, j)\n`)
  codecs.push(
    `write_${s} : Str, Value -> [Written(Try(Str, Str)), NoType]\nwrite_${s} = |ty, v| match ty {\n` +
      types.map((t) => `\t${roc(t)} => Written(written(${module}.decode_${snake(t)}(v), ${module}.to_json_${snake(t)}))\n`).join("") +
      `\t_ => NoType\n}\n\n` +
      `read_${s} : Str, JsonValue -> [Read(Try(Value, Str)), NoType]\nread_${s} = |ty, j| match ty {\n` +
      types.map((t) => `\t${roc(t)} => Read(${module}.from_json_${snake(t)}(j).map_ok(${module}.encode_${snake(t)}).map_err(Decode.message))\n`).join("") +
      `\t_ => NoType\n}\n`,
  )
}
writeFileSync(join(out, "main.roc"), `# GENERATED by fuzz/roc/gen_json_schemas.ts. Do not edit.\npackage [JsonSchemas, ${modules.join(", ")}] { haus: "../../../roc/package/main.roc" }\n`)
writeFileSync(
  join(out, "JsonSchemas.roc"),
  `# GENERATED by fuzz/roc/gen_json_schemas.ts. Do not edit.
import haus.Value
import haus.Decode
import haus.Encode
import haus.JsonValue
${modules.map((m) => `import ${m}\n`).join("")}
JsonSchemas := [].{
\t## Decode \`v\` with the type \`ty\` of the schema \`suite\`, and write the result as plain JSON.
\twrite : Str, Str, Value -> [Written(Try(Str, Str)), NoType]
\twrite = |suite, ty, v| match suite {
${writes.join("")}\t\t_ => NoType
\t}

\t## Read \`j\` as plain JSON with the type \`ty\` of the schema \`suite\`, and encode the result.
\tread : Str, Str, JsonValue -> [Read(Try(Value, Str)), NoType]
\tread = |suite, ty, j| match suite {
${reads.join("")}\t\t_ => NoType
\t}
}

## The decoded value written as JSON text.
written : Try(a, Decode.Error), (a -> Try(JsonValue, Encode.Error)) -> Try(Str, Str)
written = |decoded, to_json| match decoded {
\tOk(x) => match to_json(x) {
\t\tOk(j) => JsonValue.to_str(j).map_err(Encode.message)
\t\tErr(e) => Err("can't write it: \${Encode.message(e)}")
\t}
\tErr(e) => Err("can't decode: \${Decode.message(e)}")
}

${codecs.join("\n")}`,
)
console.log(`wrote ${out}: ${modules.join(", ")}`)
