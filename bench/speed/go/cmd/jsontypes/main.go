// Command jsontypes generates the JSON baselines of the typed tasks: Go
// types from each source's JSON Schema (bench/.out/<source>/corpus/
// <source>.schema.json, which convert writes from the haus schema's types
// through its JSON mapping, and the TypeScript validators are built from),
// as a Go code generator for JSON Schema writes them, for encoding/json and
// for goccy/go-json:
//
//	String, Int, Float64, Bool       string, int64, float64, bool
//	Instant (date-time)              time.Time (its UnmarshalJSON checks RFC 3339)
//	Date (date)                      date, a string checked with time.Parse(time.DateOnly)
//	an enum                          a string type (the values aren't checked)
//	Any                              any
//	Maybe T                          *T (T itself where nil is its null: a slice, a map, any)
//	Array T, Map V                   []T, map[string]V
//	a record                         a struct: a required member as T, an optional one as *T
//	                                 (or T where nil is its null), `omitzero`; members it
//	                                 doesn't list are ignored (encoding/json's default)
//	a variant by a member            a struct holding one of its case structs (an interface),
//	                                 with UnmarshalJSON (reads the member, then the case)
//	                                 and MarshalJSON (the case)
//	a variant by required keys       the same, the case picked by which keys are there
//	                                 (exactly one case's, as convert's reader asks); a case
//	                                 struct embeds its payload's type
//
// Each source is one package per library under jsontypes/gen/ (git-ignored),
// whose init registers the documents' root types with package jsontypes;
// jsontypes_gen.go imports them into the benchmark. Run it after convert:
//
//	go generate        (in bench/speed/go; or go run ./cmd/jsontypes)
//
// HAUS_BENCH_OUT is the results directory convert wrote to (default
// bench/.out). Types are written for every source exported there.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"unicode"

	haus "github.com/betalyra/haus-fmt/go"

	"github.com/betalyra/haus-fmt/bench/speed/go/jsontypes"
)

const module = "github.com/betalyra/haus-fmt/bench/speed/go"

// lib is a JSON library the types are generated for.
type lib struct {
	dir, constant, importPath string
}

var libs = []lib{
	{dir: "encodingjson", constant: "jsontypes.EncodingJSON", importPath: "encoding/json"},
	{dir: "gojson", constant: "jsontypes.GoJSON", importPath: "github.com/goccy/go-json"},
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "error:", err)
		os.Exit(1)
	}
}

func run() error {
	wd, err := os.Getwd()
	if err != nil {
		return err
	}
	bench, err := benchDir(wd)
	if err != nil {
		return err
	}
	out := filepath.Join(bench, ".out")
	if o := os.Getenv("HAUS_BENCH_OUT"); o != "" {
		out = o
	}
	moduleDir := filepath.Join(bench, "speed", "go")
	entries, err := os.ReadDir(out)
	if err != nil {
		return fmt.Errorf("%w: run convert first", err)
	}
	var imports []string
	for _, e := range entries {
		source := e.Name()
		schemaPath := filepath.Join(out, source, "corpus", source+".schema.json")
		if _, err := os.Stat(schemaPath); err != nil {
			continue
		}
		file, err := jsontypes.ReadFile(schemaPath)
		if err != nil {
			return err
		}
		roots, err := rootsOf(filepath.Join(out, source, "corpus", "index.haus"))
		if err != nil {
			return err
		}
		pkg := packageName(source)
		for _, l := range libs {
			code, err := generate(file, source, pkg, roots, l)
			if err != nil {
				return fmt.Errorf("%s (%s): %w", source, l.importPath, err)
			}
			dir := filepath.Join(moduleDir, "jsontypes", "gen", l.dir, pkg)
			if err := os.MkdirAll(dir, 0o755); err != nil {
				return err
			}
			path := filepath.Join(dir, "types.go")
			if err := os.WriteFile(path, code, 0o644); err != nil {
				return err
			}
			imports = append(imports, module+"/jsontypes/gen/"+l.dir+"/"+pkg)
			fmt.Printf("%s: %d bytes\n", path, len(code))
		}
	}
	if len(imports) == 0 {
		return fmt.Errorf("no exported corpus in %s: run convert first", out)
	}
	slices.Sort(imports)
	var b bytes.Buffer
	b.WriteString("// Code generated by cmd/jsontypes; DO NOT EDIT.\n\n")
	b.WriteString("package speed\n\n// The JSON baselines of the typed tasks: each package registers its types.\nimport (\n")
	for _, p := range imports {
		fmt.Fprintf(&b, "\t_ %q\n", p)
	}
	b.WriteString(")\n")
	code, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(moduleDir, "jsontypes_gen.go"), code, 0o644)
}

// benchDir finds bench/ (the directory holding sources.haus) from dir up.
func benchDir(dir string) (string, error) {
	for d := dir; ; {
		if _, err := os.Stat(filepath.Join(d, "sources.haus")); err == nil {
			return d, nil
		}
		up := filepath.Dir(d)
		if up == d {
			return "", fmt.Errorf("no sources.haus in %s or above it", dir)
		}
		d = up
	}
}

// rootsOf returns the documents' root types of an export's index, each once.
func rootsOf(index string) ([]string, error) {
	text, err := os.ReadFile(index)
	if err != nil {
		return nil, err
	}
	v, err := haus.Parse(text)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", index, err)
	}
	get := func(v haus.Value, key string) (haus.Value, bool) {
		r, ok := v.(haus.Record)
		if !ok {
			return nil, false
		}
		return r.Get(key)
	}
	docs, ok := get(v, "documents")
	arr, isArr := docs.(haus.Array)
	if !ok || !isArr {
		return nil, fmt.Errorf("%s: no documents", index)
	}
	var roots []string
	for _, d := range arr {
		r, ok := get(d, "root")
		s, isStr := r.(haus.String)
		if !ok || !isStr {
			return nil, fmt.Errorf("%s: a document without a root", index)
		}
		if !slices.Contains(roots, string(s)) {
			roots = append(roots, string(s))
		}
	}
	return roots, nil
}

func packageName(source string) string {
	return strings.Map(func(r rune) rune {
		if unicode.IsLetter(r) || unicode.IsDigit(r) {
			return unicode.ToLower(r)
		}
		return -1
	}, source)
}

// ident turns a name or a JSON key into an exported Go identifier.
func ident(s string) string {
	var b strings.Builder
	up := true
	for _, r := range s {
		if r < unicode.MaxASCII && (unicode.IsLetter(r) || unicode.IsDigit(r)) {
			if up {
				r = unicode.ToUpper(r)
			}
			b.WriteRune(r)
			up = false
		} else {
			up = true
		}
	}
	id := b.String()
	if id == "" || unicode.IsDigit(rune(id[0])) {
		id = "X" + id
	}
	return id
}

// typeInfo is a Go type expression and what it is.
type typeInfo struct {
	expr string
	// nilable: nil is its null (a pointer, slice, map, any).
	nilable bool
	// kind: "struct" (a record), "variant", "any", or "" (anything else).
	kind string
	// structName is the struct a value of the type holds by value, for
	// telling recursive types (which need a pointer).
	structName string
}

func nullable(t typeInfo) typeInfo {
	if t.nilable {
		return t
	}
	return typeInfo{expr: "*" + t.expr, nilable: true, kind: "pointer"}
}

type field struct {
	name, expr, tag string
	embedded        bool
	// valueStruct is the struct the field holds by value, if any.
	valueStruct string
}

type structDecl struct {
	name, doc string
	fields    []*field
}

// gen generates one source's types for one library.
type gen struct {
	file    *jsontypes.File
	lib     lib
	used    map[string]bool
	refs    map[string]typeInfo
	pending []func() error
	// decls are the declarations in order: text, or a struct (written
	// after recursive fields get their pointers).
	decls   []any
	structs map[string]*structDecl
	needs   map[string]bool
}

func generate(file *jsontypes.File, source, pkg string, roots []string, l lib) ([]byte, error) {
	g := &gen{file: file, lib: l, used: map[string]bool{}, refs: map[string]typeInfo{}, structs: map[string]*structDecl{}, needs: map[string]bool{}}
	rootTypes := make([]string, len(roots))
	for i, r := range roots {
		if g.file.Definitions.Get(r) == nil {
			return nil, fmt.Errorf("no definition %s", r)
		}
		t, err := g.ref(r)
		if err != nil {
			return nil, err
		}
		rootTypes[i] = t.expr
	}
	for len(g.pending) > 0 {
		next := g.pending[0]
		g.pending = g.pending[1:]
		if err := next(); err != nil {
			return nil, err
		}
	}
	g.pointRecursiveFields()

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by cmd/jsontypes from %s.schema.json; DO NOT EDIT.\n\n", source)
	fmt.Fprintf(&b, "// Package %s holds the types of %s's documents for %s: the JSON baseline of the typed tasks.\n", pkg, source, l.importPath)
	fmt.Fprintf(&b, "package %s\n\nimport (\n", pkg)
	if g.needs["errors"] {
		b.WriteString("\t\"errors\"\n")
	}
	if g.needs["fmt"] {
		b.WriteString("\t\"fmt\"\n")
	}
	if g.needs["time"] {
		b.WriteString("\t\"time\"\n")
	}
	fmt.Fprintf(&b, "\n\tjson %q\n\n\t%q\n)\n\n", l.importPath, module+"/jsontypes")
	b.WriteString("func init() {\n")
	fmt.Fprintf(&b, "\tjsontypes.Register(%s, %q, jsontypes.Source{\n\t\tSchemaSHA256: %q,\n\t\tRoots: map[string]jsontypes.Codec{\n", l.constant, source, file.SHA256)
	for i, r := range roots {
		fmt.Fprintf(&b, "\t\t\t%q: codec[%s](),\n", r, rootTypes[i])
	}
	b.WriteString("\t\t},\n\t})\n}\n\n")
	b.WriteString(`func codec[T any]() jsontypes.Codec {
	return jsontypes.Codec{
		Decode: func(b []byte) (any, error) {
			v := new(T)
			return v, json.Unmarshal(b, v)
		},
		Encode: func(v any) ([]byte, error) { return json.Marshal(v.(*T)) },
	}
}

`)
	if g.needs["errors"] {
		b.WriteString("var errNoCase = errors.New(\"a variant without its case\")\n\n")
	}
	if g.needs["seen"] {
		b.WriteString(`// seen is true when its member is there (whatever its value).
type seen bool

func (s *seen) UnmarshalJSON([]byte) error {
	*s = true
	return nil
}

`)
	}
	if g.needs["date"] {
		b.WriteString(`// date is a JSON Schema date (format: date), checked by time.Parse(time.DateOnly).
type date string

func (d *date) UnmarshalJSON(b []byte) error {
	var s string
	if err := json.Unmarshal(b, &s); err != nil {
		return err
	}
	if _, err := time.Parse(time.DateOnly, s); err != nil {
		return err
	}
	*d = date(s)
	return nil
}

`)
	}
	for _, d := range g.decls {
		switch d := d.(type) {
		case string:
			b.WriteString(d)
			b.WriteString("\n")
		case *structDecl:
			if d.doc != "" {
				fmt.Fprintf(&b, "// %s\n", d.doc)
			}
			fmt.Fprintf(&b, "type %s struct {\n", d.name)
			for _, f := range d.fields {
				if f.embedded {
					fmt.Fprintf(&b, "\t%s\n", f.expr)
				} else {
					fmt.Fprintf(&b, "\t%s %s `json:%q`\n", f.name, f.expr, f.tag)
				}
			}
			b.WriteString("}\n\n")
		}
	}
	code, err := format.Source(b.Bytes())
	if err != nil {
		return b.Bytes(), fmt.Errorf("the generated code doesn't format: %w", err)
	}
	return code, nil
}

// typeIdent turns a type name (Name_member…) into a Go identifier: ident
// of each part, the underscores kept.
func typeIdent(s string) string {
	parts := strings.Split(s, "_")
	for i, p := range parts {
		parts[i] = ident(p)
	}
	return strings.Join(parts, "_")
}

// newName returns an unused Go type name from base.
func (g *gen) newName(base string) string {
	name := typeIdent(base)
	for i := 2; g.used[name]; i++ {
		name = fmt.Sprintf("%s%d", typeIdent(base), i)
	}
	g.used[name] = true
	return name
}

// ref is the type of a definition: an alias ($ref) or Any is the type it
// stands for; anything else gets a named type, declared later (so a type
// can refer to itself).
func (g *gen) ref(name string) (typeInfo, error) {
	if t, ok := g.refs[name]; ok {
		return t, nil
	}
	n := g.file.Definitions.Get(name)
	if n == nil {
		return typeInfo{}, fmt.Errorf("no definition %s", name)
	}
	if target, ok := jsontypes.RefName(n); ok {
		t, err := g.ref(target)
		g.refs[name] = t
		return t, err
	}
	if n.IsAny() {
		t := typeInfo{expr: "any", nilable: true, kind: "any"}
		g.refs[name] = t
		return t, nil
	}
	shape, null := n, false
	if x := n.NullOr(); x != nil {
		if _, isRef := jsontypes.RefName(x); isRef || x.IsAny() {
			t, err := g.goType(x, name)
			t = nullable(t)
			g.refs[name] = t
			return t, err
		}
		shape, null = x, true
	}
	goName := g.newName(name)
	t, err := g.shapeOf(shape, goName)
	if err != nil {
		return t, err
	}
	if _, tnull := shape.Type(); null || tnull {
		t = nullable(t)
	}
	g.refs[name] = t
	g.pending = append(g.pending, func() error { return g.declare(goName, shape, "") })
	return t, nil
}

// shapeOf is what a named type declared for the schema is.
func (g *gen) shapeOf(n *jsontypes.Node, goName string) (typeInfo, error) {
	if n.Discriminator() != "" || n.Keyed() != nil {
		return typeInfo{expr: goName, kind: "variant"}, nil
	}
	t, _ := n.Type()
	switch t {
	case "object":
		if n.Get("additionalProperties") != nil {
			return typeInfo{expr: goName, nilable: true}, nil
		}
		return typeInfo{expr: goName, kind: "struct", structName: goName}, nil
	case "array":
		return typeInfo{expr: goName, nilable: true}, nil
	case "string", "integer", "number", "boolean":
		return typeInfo{expr: goName}, nil
	}
	return typeInfo{}, fmt.Errorf("a definition the generator doesn't read: %s", describe(n))
}

func describe(n *jsontypes.Node) string {
	return fmt.Sprintf("keys %v", n.Keys)
}

// declare declares goName as the type of the schema (not null).
func (g *gen) declare(goName string, n *jsontypes.Node, doc string) error {
	if n.Discriminator() != "" {
		return g.discriminated(goName, n)
	}
	if n.Keyed() != nil {
		return g.keyed(goName, n)
	}
	t, _ := n.Type()
	switch t {
	case "object":
		if ap := n.Get("additionalProperties"); ap != nil {
			v, err := g.goType(ap, goName+"Value")
			if err != nil {
				return err
			}
			g.decls = append(g.decls, fmt.Sprintf("type %s map[string]%s\n", goName, v.expr))
			return nil
		}
		return g.record(goName, n, doc)
	case "array":
		item, err := g.goType(n.Get("items"), goName+"Item")
		if err != nil {
			return err
		}
		g.decls = append(g.decls, fmt.Sprintf("type %s []%s\n", goName, item.expr))
		return nil
	}
	p, err := g.primitive(n)
	if err != nil {
		return err
	}
	if strings.HasPrefix(p, "time.") || p == "date" {
		// An alias: a defined type would lose the type's UnmarshalJSON.
		g.decls = append(g.decls, fmt.Sprintf("type %s = %s\n", goName, p))
	} else {
		g.decls = append(g.decls, fmt.Sprintf("type %s %s\n", goName, p))
	}
	return nil
}

func (g *gen) primitive(n *jsontypes.Node) (string, error) {
	t, _ := n.Type()
	switch t {
	case "string":
		switch f, _ := n.Str("format"); f {
		case "date-time":
			g.needs["time"] = true
			return "time.Time", nil
		case "date":
			g.needs["time"], g.needs["date"] = true, true
			return "date", nil
		case "":
			return "string", nil
		default:
			return "", fmt.Errorf("format %s", f)
		}
	case "integer":
		return "int64", nil
	case "number":
		return "float64", nil
	case "boolean":
		return "bool", nil
	}
	return "", fmt.Errorf("a schema the generator doesn't read: %s", describe(n))
}

// goType is the type of a schema in place; records and variants written
// in place get a type named from hint.
func (g *gen) goType(n *jsontypes.Node, hint string) (typeInfo, error) {
	if name, ok := jsontypes.RefName(n); ok {
		return g.ref(name)
	}
	if n.IsAny() {
		return typeInfo{expr: "any", nilable: true, kind: "any"}, nil
	}
	if x := n.NullOr(); x != nil {
		t, err := g.goType(x, hint)
		return nullable(t), err
	}
	if _, ok := n.Str("const"); ok {
		return typeInfo{expr: "string"}, nil
	}
	t, null := n.Type()
	var out typeInfo
	switch {
	case n.Discriminator() != "" || n.Keyed() != nil:
		name := g.newName(hint)
		if err := g.declare(name, n, ""); err != nil {
			return out, err
		}
		out = typeInfo{expr: name, kind: "variant"}
	case t == "object" && n.Get("additionalProperties") != nil:
		v, err := g.goType(n.Get("additionalProperties"), hint+"Value")
		if err != nil {
			return out, err
		}
		out = typeInfo{expr: "map[string]" + v.expr, nilable: true}
	case t == "object":
		name := g.newName(hint)
		if err := g.record(name, n, ""); err != nil {
			return out, err
		}
		out = typeInfo{expr: name, kind: "struct", structName: name}
	case t == "array":
		item, err := g.goType(n.Get("items"), hint+"Item")
		if err != nil {
			return out, err
		}
		out = typeInfo{expr: "[]" + item.expr, nilable: true}
	default:
		p, err := g.primitive(n)
		if err != nil {
			return out, err
		}
		out = typeInfo{expr: p}
	}
	if null {
		out = nullable(out)
	}
	return out, nil
}

// validTag reports whether encoding/json takes key as a field's name in a
// tag (its isValidTag).
func validTag(key string) bool {
	if key == "" || key == "-" {
		return false
	}
	for _, c := range key {
		if !strings.ContainsRune("!#$%&()*+-./:;<=>?@[]^_{|}~ ", c) && !unicode.IsLetter(c) && !unicode.IsDigit(c) {
			return false
		}
	}
	return true
}

// record declares a struct for a record (or a case of a variant by a
// member: its member is a property with a const).
func (g *gen) record(name string, n *jsontypes.Node, doc string) error {
	s := &structDecl{name: name, doc: doc}
	g.structs[name] = s
	g.decls = append(g.decls, s)
	required := map[string]bool{}
	for _, k := range n.Strings("required") {
		required[k] = true
	}
	fieldNames := map[string]bool{}
	props := n.Get("properties")
	if props == nil {
		return nil
	}
	for _, key := range props.Keys {
		if !validTag(key) {
			return fmt.Errorf("%s: the member %q can't be a struct tag's name", name, key)
		}
		t, err := g.goType(props.Members[key], name+"_"+ident(key))
		if err != nil {
			return fmt.Errorf("%s.%s: %w", name, key, err)
		}
		fname := ident(key)
		for i := 2; fieldNames[fname]; i++ {
			fname = fmt.Sprintf("%s%d", ident(key), i)
		}
		fieldNames[fname] = true
		f := &field{name: fname, tag: key}
		if required[key] {
			f.expr, f.valueStruct = t.expr, t.structName
		} else {
			f.expr, f.tag = nullable(t).expr, key+",omitzero"
		}
		s.fields = append(s.fields, f)
	}
	return nil
}

// discriminated declares a variant told apart by a member: a struct holding
// its case, with UnmarshalJSON and MarshalJSON.
func (g *gen) discriminated(name string, n *jsontypes.Node) error {
	member := n.Discriminator()
	if !validTag(member) {
		return fmt.Errorf("%s: the member %q can't be a struct tag's name", name, member)
	}
	iface := g.newName(name + "Case")
	var cases, consts []string
	for _, b := range n.Get("oneOf").Items {
		c, ok := b.Get("properties").Get(member).Str("const")
		if !ok {
			return fmt.Errorf("%s: a case without its %s", name, member)
		}
		cname := g.newName(name + "_" + ident(c))
		if err := g.record(cname, b, fmt.Sprintf("%s is the case of %s whose %s is %q.", cname, name, member, c)); err != nil {
			return err
		}
		cases, consts = append(cases, cname), append(consts, c)
	}
	g.needs["errors"], g.needs["fmt"] = true, true
	var b strings.Builder
	g.variantHead(&b, name, iface, cases, fmt.Sprintf("told apart by its member %q", member))
	fmt.Fprintf(&b, "func (u *%s) UnmarshalJSON(b []byte) error {\n", name)
	fmt.Fprintf(&b, "\tvar probe struct {\n\t\tTag string `json:%q`\n\t}\n", member)
	b.WriteString("\tif err := json.Unmarshal(b, &probe); err != nil {\n\t\treturn err\n\t}\n")
	fmt.Fprintf(&b, "\tvar c %s\n\tswitch probe.Tag {\n", iface)
	for i, c := range cases {
		fmt.Fprintf(&b, "\tcase %q:\n\t\tc = new(%s)\n", consts[i], c)
	}
	fmt.Fprintf(&b, "\tdefault:\n\t\treturn fmt.Errorf(\"%s: no case %%q\", probe.Tag)\n\t}\n", name)
	g.variantTail(&b, name)
	return nil
}

// keyed declares a variant told apart by required keys.
func (g *gen) keyed(name string, n *jsontypes.Node) error {
	iface := g.newName(name + "Case")
	cs := n.Keyed()
	var keys []string
	for _, c := range cs {
		for _, k := range c.Keys {
			if !validTag(k) {
				return fmt.Errorf("%s: the key %q can't be a struct tag's name", name, k)
			}
			if !slices.Contains(keys, k) {
				keys = append(keys, k)
			}
		}
	}
	var cases []string
	for _, c := range cs {
		base := strings.Join(c.Keys, "_")
		if target, ok := jsontypes.RefName(c.Payload); ok {
			base = target
		}
		cname := g.newName(name + "_" + ident(base))
		if err := g.keyedCase(cname, c, fmt.Sprintf("%s is %s's case with the keys %v.", cname, name, c.Keys)); err != nil {
			return err
		}
		cases = append(cases, cname)
	}
	g.needs["errors"], g.needs["fmt"], g.needs["seen"] = true, true, true
	var b strings.Builder
	g.variantHead(&b, name, iface, cases, "told apart by which keys it has")
	fmt.Fprintf(&b, "func (u *%s) UnmarshalJSON(b []byte) error {\n\tvar probe struct {\n", name)
	for i, k := range keys {
		fmt.Fprintf(&b, "\t\tK%d seen `json:%q`\n", i, k)
	}
	b.WriteString("\t}\n\tif err := json.Unmarshal(b, &probe); err != nil {\n\t\treturn err\n\t}\n")
	fmt.Fprintf(&b, "\tvar c %s\n\tn := 0\n", iface)
	for i, c := range cs {
		var conds []string
		for _, k := range c.Keys {
			conds = append(conds, fmt.Sprintf("bool(probe.K%d)", slices.Index(keys, k)))
		}
		if len(conds) == 0 {
			conds = []string{"true"}
		}
		fmt.Fprintf(&b, "\tif %s {\n\t\tc, n = new(%s), n+1\n\t}\n", strings.Join(conds, " && "), cases[i])
	}
	fmt.Fprintf(&b, "\tif n != 1 {\n\t\treturn fmt.Errorf(\"%s: the keys of %%d cases\", n)\n\t}\n", name)
	g.variantTail(&b, name)
	return nil
}

// keyedCase declares a case of a variant by keys: a struct embedding its
// payload's type (so its members are the case's), or the payload's map
// type.
func (g *gen) keyedCase(cname string, c jsontypes.KeyedCase, doc string) error {
	if _, ok := jsontypes.RefName(c.Payload); !ok {
		if c.Payload.IsAny() {
			g.decls = append(g.decls, fmt.Sprintf("// %s\ntype %s map[string]any\n", doc, cname))
			return nil
		}
		return g.declare(cname, c.Payload, doc)
	}
	t, err := g.goType(c.Payload, cname+"Payload")
	if err != nil {
		return err
	}
	switch {
	case t.kind == "any":
		g.decls = append(g.decls, fmt.Sprintf("// %s\ntype %s map[string]any\n", doc, cname))
	case t.kind == "struct" || t.kind == "variant" || (t.kind == "pointer" && !strings.HasPrefix(t.expr, "*[]")):
		s := &structDecl{name: cname, doc: doc, fields: []*field{{expr: t.expr, embedded: true, valueStruct: t.structName}}}
		g.structs[cname] = s
		g.decls = append(g.decls, s)
	case strings.HasPrefix(t.expr, "map[") || t.nilable && t.kind == "":
		g.decls = append(g.decls, fmt.Sprintf("// %s\ntype %s %s\n", doc, cname, t.expr))
	default:
		return fmt.Errorf("%s: a case whose payload isn't an object (%s)", cname, t.expr)
	}
	return nil
}

func (g *gen) variantHead(b *strings.Builder, name, iface string, cases []string, how string) {
	fmt.Fprintf(b, "// %s is a variant %s: Value is one of its cases.\ntype %s struct {\n\tValue %s\n}\n\n", name, how, name, iface)
	fmt.Fprintf(b, "// %s is a case of %s.\ntype %s interface {\n\tis%s()\n}\n\n", iface, name, iface, name)
	for _, c := range cases {
		fmt.Fprintf(b, "func (%s) is%s() {}\n", c, name)
	}
	b.WriteString("\n")
}

func (g *gen) variantTail(b *strings.Builder, name string) {
	b.WriteString("\tif err := json.Unmarshal(b, c); err != nil {\n\t\treturn err\n\t}\n\tu.Value = c\n\treturn nil\n}\n\n")
	fmt.Fprintf(b, "func (u %s) MarshalJSON() ([]byte, error) {\n\tif u.Value == nil {\n\t\treturn nil, errNoCase\n\t}\n\treturn json.Marshal(u.Value)\n}\n", name)
	g.decls = append(g.decls, b.String())
}

// pointRecursiveFields makes the fields that would make a struct hold
// itself by value pointers (Go rejects such types).
func (g *gen) pointRecursiveFields() {
	const (
		unvisited = iota
		visiting
		done
	)
	state := map[string]int{}
	var visit func(name string)
	visit = func(name string) {
		state[name] = visiting
		s := g.structs[name]
		for _, f := range s.fields {
			if f.valueStruct == "" || g.structs[f.valueStruct] == nil {
				continue
			}
			switch state[f.valueStruct] {
			case visiting:
				f.expr, f.valueStruct = "*"+f.expr, ""
			case unvisited:
				visit(f.valueStruct)
			}
		}
		state[name] = done
	}
	names := make([]string, 0, len(g.structs))
	for _, d := range g.decls {
		if s, ok := d.(*structDecl); ok {
			names = append(names, s.name)
		}
	}
	for _, n := range names {
		if state[n] == unvisited {
			visit(n)
		}
	}
}
