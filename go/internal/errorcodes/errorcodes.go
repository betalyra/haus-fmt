// Package errorcodes generates the Go table of error codes (error_codes.go in
// the haus package) from the catalogue, spec/errors.haus, which it reads with
// the haus parser itself.
package errorcodes

import (
	"bytes"
	"fmt"
	"go/format"
	"strconv"
	"strings"

	haus "github.com/betalyra/haus-fmt/go"
)

// Entry is one code of the catalogue.
type Entry struct {
	Code     string
	Category string
	Means    string
	Fix      string
}

// Read parses the catalogue.
func Read(src []byte) ([]Entry, error) {
	values, err := haus.ParseAll(src)
	if err != nil {
		return nil, err
	}
	entries := make([]Entry, 0, len(values))
	for i, v := range values {
		code, ok := v.(haus.Variant)
		if !ok || code.Tag.String() != "Code" || len(code.Args) != 1 {
			return nil, fmt.Errorf("entry %d is not Code { … }", i)
		}
		rec, ok := code.Args[0].(haus.Record)
		if !ok {
			return nil, fmt.Errorf("entry %d is not Code { … }", i)
		}
		str := func(key string) (string, error) {
			v, ok := rec.Get(key)
			s, isString := v.(haus.String)
			if !ok || !isString {
				return "", fmt.Errorf("entry %d: %s is not a string", i, key)
			}
			return string(s), nil
		}
		var e Entry
		if e.Code, err = str("code"); err != nil {
			return nil, err
		}
		if e.Means, err = str("means"); err != nil {
			return nil, err
		}
		if e.Fix, err = str("fix"); err != nil {
			return nil, err
		}
		cat, _ := rec.Get("category")
		c, isTag := cat.(haus.Variant)
		if !isTag || len(c.Args) != 0 {
			return nil, fmt.Errorf("entry %d: category is not a tag", i)
		}
		e.Category = c.Tag.String()
		entries = append(entries, e)
	}
	return entries, nil
}

// initialisms are written in capitals in Go names.
var initialisms = map[string]string{"utf8": "UTF8", "json": "JSON"}

// ConstName returns the Go name of a code: invalid-utf8 is CodeInvalidUTF8.
func ConstName(code string) string {
	var b strings.Builder
	b.WriteString("Code")
	for _, part := range strings.Split(code, "-") {
		if s, ok := initialisms[part]; ok {
			b.WriteString(s)
			continue
		}
		b.WriteString(strings.ToUpper(part[:1]) + part[1:])
	}
	return b.String()
}

// Generate returns the Go source of error_codes.go for the catalogue.
func Generate(src []byte) ([]byte, error) {
	entries, err := Read(src)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/gen/errorcodes from spec/errors.haus. DO NOT EDIT.\n")
	b.WriteString("// To change a code, edit spec/errors.haus and run `go generate` in go/.\n\n")
	b.WriteString("package haus\n\n")
	b.WriteString("// The error codes of the catalogue (spec §17).\nconst (\n")
	for _, e := range entries {
		fmt.Fprintf(&b, "\t// %s is %q: %s\n", ConstName(e.Code), e.Code, oneLine(e.Means))
		fmt.Fprintf(&b, "\t%s ErrorCode = %q\n", ConstName(e.Code), e.Code)
	}
	b.WriteString(")\n\n")
	cats := []string{}
	seen := map[string]bool{}
	for _, e := range entries {
		if !seen[e.Category] {
			seen[e.Category] = true
			cats = append(cats, e.Category)
		}
	}
	b.WriteString("// The categories of the catalogue.\nconst (\n")
	for _, c := range cats {
		fmt.Fprintf(&b, "\tCategory%s ErrorCategory = %q\n", c, c)
	}
	b.WriteString(")\n\n")
	b.WriteString("var errorCodeList = []ErrorCode{\n")
	for _, e := range entries {
		fmt.Fprintf(&b, "\t%s,\n", ConstName(e.Code))
	}
	b.WriteString("}\n\n")
	b.WriteString("var errorCatalogue = map[ErrorCode]ErrorInfo{\n")
	for _, e := range entries {
		fmt.Fprintf(&b, "\t%s: {Category%s, %s, %s},\n", ConstName(e.Code), e.Category,
			strconv.Quote(e.Means), strconv.Quote(e.Fix))
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

func oneLine(s string) string {
	return strings.Join(strings.Fields(s), " ")
}
