//! Rust code from a schema: one item per named type, with `Decode` and
//! `Encode` implementations that check every rule of the schema, and
//! `FromJson` and `ToJson` for its schema-based JSON (spec §16.3).
//!
//! | haus                         | Rust                                     |
//! |------------------------------|------------------------------------------|
//! | `{ a: T, b?: U }`            | `struct { a: T, b: Option<U> }`          |
//! | `< A \| B T \| C { … } >`    | `enum { A, B(T), C { … }, Unknown(…) }`  |
//! | `closed < Tag T U >`         | `struct Tag(T, U)`                       |
//! | `< >`                        | `haus::AnyTag`                           |
//! | `Maybe a`, `Result e a`      | `Option<A>`, `Result<A, E>`              |
//! | `Array a`, `Map v`           | `Vec<A>`, `BTreeMap<String, V>`          |
//! | `Any`, `Secret a`            | `haus::Value`, `haus::Secret<A>`         |
//!
//! `@deprecated` types, fields and tags get `#[deprecated]`. The generated
//! code itself allows their use, so only code that touches them is warned.
//!
//! Records and variants written inline get a name from where they are:
//! `Order.status` becomes `OrderStatus`. The code is built as tokens with
//! `quote!` and printed with `prettyplease`.

use crate::schema::{Attribute, Case, Error, Field, File, PRELUDE, Ty, TypeDef, deprecation, error};
use proc_macro2::{Ident, Literal, Span, TokenStream};
use quote::{ToTokens, format_ident, quote};
use std::collections::{HashMap, HashSet};

/// A type imported from std/time or a schema package.
#[derive(Debug, Clone)]
pub struct Imported {
    /// `std/time#Date`, `@haus-fmt/money@1#Money`.
    pub id: String,
    /// The Rust path: `::haus::time::Date`, `::haus_money::Money`.
    pub path: String,
    pub params: usize,
}

/// A codec: the Rust type (implementing `haus::Codec`) used for the type with this id.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Codec {
    /// `@haus-fmt/money@1#Money`.
    pub id: String,
    /// `crate::codecs::Cents`.
    pub path: String,
}

pub struct Input<'a> {
    pub text: &'a str,
    /// The file's id: `@haus-fmt/money@1`, `order-app/src/order`.
    pub id: &'a str,
    /// Imported types by name.
    pub imports: &'a HashMap<String, Imported>,
    pub codecs: &'a [Codec],
}

pub(crate) use crate::schema::{STD_TIME, unknown_type};
use haus::ErrorCode as Code;

pub fn generate(file: &File, input: &Input) -> Result<String, Error> {
    let fail = |pos, reason: String| Err(error(input.text, pos, Code::UnknownType, reason));
    let ids = known_ids(file, input);
    if let Some(codec) = input.codecs.iter().find(|c| !ids.contains(&c.id)) {
        return fail(
            0,
            format!("a codec for {}, but the schema has no such type (it has {})", codec.id, ids.join(", ")),
        );
    }
    let codecs = input
        .codecs
        .iter()
        .map(|c| {
            Ok((
                c.id.as_str(),
                rust_path(&c.path)
                    .ok_or_else(|| error(input.text, 0, Code::UnknownType, format!("{} is not a Rust path", c.path)))?,
            ))
        })
        .collect::<Result<HashMap<_, _>, Error>>()?;

    let defs: HashMap<&str, &TypeDef> = file.types.iter().map(|d| (d.name.as_str(), d)).collect();
    let mut g = Gen {
        input,
        reach: reach(&defs),
        cyclic: cyclic_aliases(&defs),
        tagged_maybes: tagged_maybes(&defs),
        defs,
        names: file.types.iter().map(|d| d.name.clone()).collect(),
        codecs,
        items: vec![],
    };
    file.types.iter().try_for_each(|def| g.define_named(def))?;

    let checks = g.codecs.iter().map(|(id, path)| {
        let message = format!("{path} is a codec for another type than {id}");
        quote! {
            const _: () = ::core::assert!(::haus::same_id(<#path as ::haus::Codec>::ID, #id), #message);
        }
    });
    let items = &g.items;
    let tokens = quote! { #(#items)* #(#checks)* };
    let code = syn::parse2::<syn::File>(tokens)
        .map_err(|e| error(input.text, 0, Code::SchemaSyntax, format!("haus-fmt-build generated invalid Rust: {e}")))?;
    Ok(format!("// Generated by haus-fmt-build from {}. Don't edit.\n\n{}", input.id, prettyplease::unparse(&code)))
}

/// Every id a codec could target: this file's types and the imported ones.
fn known_ids(file: &File, input: &Input) -> Vec<String> {
    let own = file.types.iter().map(|d| format!("{}#{}", input.id, d.name));
    own.chain(input.imports.values().map(|i| i.id.clone())).collect()
}

/// A Rust path or type, as written in a codec or an import: `crate::codecs::Cents`.
fn rust_path(path: &str) -> Option<TokenStream> {
    syn::parse_str::<syn::Type>(path).ok().map(|t| quote!(#t))
}

// ── recursion ────────────────────────────────────────────────

/// The types each type contains directly (not behind an array or map), transitively.
/// A reference from `a` to `b` needs a `Box` if `b` reaches `a`.
fn reach<'a>(defs: &HashMap<&'a str, &'a TypeDef>) -> HashMap<&'a str, HashSet<&'a str>> {
    fn direct<'a>(ty: &'a Ty, out: &mut HashSet<&'a str>) {
        match ty {
            Ty::Name { name, .. } if matches!(name.as_str(), "Array" | "Map") => {}
            Ty::Name { name, args, .. } => {
                out.insert(name);
                for a in args {
                    direct(a, out);
                }
            }
            Ty::Param { .. } => {}
            Ty::Record { fields, .. } => fields.iter().for_each(|f| direct(&f.ty, out)),
            Ty::Variant { cases, .. } => cases.iter().flat_map(|c| &c.payload).for_each(|t| direct(t, out)),
        }
    }
    let edges: HashMap<&str, HashSet<&str>> = defs
        .iter()
        .map(|(&name, def)| {
            let mut out = HashSet::new();
            direct(&def.ty, &mut out);
            (name, out.into_iter().filter(|n| defs.contains_key(n)).collect())
        })
        .collect();
    let reachable = |start: &str| {
        let mut seen = HashSet::new();
        let mut stack: Vec<&str> = edges[start].iter().copied().collect();
        while let Some(n) = stack.pop() {
            if seen.insert(n) {
                stack.extend(&edges[n]);
            }
        }
        seen
    };
    edges.keys().map(|&start| (start, reachable(start))).collect()
}

/// The named types a type expression refers to without passing through a
/// record or variant (which are types of their own in Rust).
fn aliased<'a>(ty: &'a Ty, out: &mut Vec<&'a str>) {
    if let Ty::Name { name, args, .. } = ty {
        out.push(name);
        args.iter().for_each(|a| aliased(a, out));
    }
}

/// Aliases (definitions that aren't a record or variant) that refer to
/// themselves through other aliases: `type Loop = Maybe Loop`, `type N = Array N`.
fn cyclic_aliases<'a>(defs: &HashMap<&'a str, &'a TypeDef>) -> HashSet<&'a str> {
    let is_alias = |name: &str| defs.get(name).is_some_and(|d| matches!(d.ty, Ty::Name { .. }));
    let refers = |name: &'a str| {
        let mut out = vec![];
        aliased(&defs[name].ty, &mut out);
        out.into_iter().filter(|n| defs.contains_key(n)).collect::<Vec<_>>()
    };
    defs.keys()
        .copied()
        .filter(|&start| is_alias(start))
        .filter(|&start| {
            let (mut seen, mut todo) = (HashSet::new(), refers(start));
            while let Some(n) = todo.pop() {
                if n == start {
                    return true;
                }
                if is_alias(n) && seen.insert(n) {
                    todo.extend(refers(n));
                }
            }
            false
        })
        .collect()
}

/// The positions of the `Maybe`s that reach themselves only through `Maybe`,
/// `Secret` and names (`type T = Maybe T`): they always use the tagged form
/// in JSON (spec §16.3), so the form never depends on where one starts.
pub(crate) fn tagged_maybes(defs: &HashMap<&str, &TypeDef>) -> HashSet<usize> {
    fn maybes(ty: &Ty, out: &mut Vec<(usize, Ty)>) {
        match ty {
            Ty::Name { name, args, pos } => {
                if name == "Maybe"
                    && let [arg] = args.as_slice()
                {
                    out.push((*pos, arg.clone()));
                }
                args.iter().for_each(|a| maybes(a, out));
            }
            Ty::Param { .. } => {}
            Ty::Record { fields, .. } => fields.iter().for_each(|f| maybes(&f.ty, out)),
            Ty::Variant { cases, .. } => cases.iter().flat_map(|c| &c.payload).for_each(|t| maybes(t, out)),
        }
    }
    let mut all = vec![];
    defs.values().for_each(|d| maybes(&d.ty, &mut all));
    all.into_iter()
        .filter(|(target, arg)| {
            let (mut seen, mut todo) = (HashSet::new(), vec![arg.clone()]);
            // Only names lead anywhere: records, variants and parameters end the search.
            while let Some(Ty::Name { name, args, pos }) = todo.pop() {
                match (name.as_str(), args.as_slice()) {
                    ("Maybe", _) if pos == *target => return true,
                    ("Maybe" | "Secret", [inner]) => todo.push(inner.clone()),
                    (name, _) => {
                        if let Some(def) = defs.get(name)
                            && seen.insert(name.to_owned())
                        {
                            todo.push(def.ty.clone());
                        }
                    }
                }
            }
            false
        })
        .map(|(pos, _)| pos)
        .collect()
}

// ── Rust types and their (de)coding ──────────────────────────

/// Decoding or encoding a value `x`: a function to call, or an expression in `x`.
#[derive(Clone)]
enum Fun {
    Path(TokenStream),
    Expr(TokenStream),
}

impl Fun {
    /// As a function value: `f`, or `|x| expr`.
    fn value(&self) -> TokenStream {
        match self {
            Fun::Path(f) => f.clone(),
            Fun::Expr(e) => quote!(|x| #e),
        }
    }

    /// Applied to `arg`.
    fn call(&self, arg: TokenStream) -> TokenStream {
        match self {
            Fun::Path(f) => quote!(#f(#arg)),
            Fun::Expr(e) => quote!({ let x = #arg; #e }),
        }
    }

    /// An encoder, which also takes the `::haus::Encoder` `__e`, as a
    /// function value: `f`, or `|x, __e| expr`.
    fn encoder(&self) -> TokenStream {
        match self {
            Fun::Path(f) => f.clone(),
            Fun::Expr(e) => quote!(|x, __e| #e),
        }
    }

    /// An encoder applied to `x`, with `__e` in scope.
    fn encode_x(&self) -> TokenStream {
        match self {
            Fun::Path(f) => quote!(#f(x, __e)),
            Fun::Expr(e) => e.clone(),
        }
    }

    /// An encoder applied to `arg`, with `__e` in scope.
    fn encode(&self, arg: TokenStream) -> TokenStream {
        match self {
            Fun::Path(f) => quote!(#f(#arg, __e)),
            Fun::Expr(e) => quote!({ let x = #arg; #e }),
        }
    }

    /// A JSON reader, which also takes the `::haus::Decoder` `__d`, as a
    /// function value: `f`, or `|x, __d| expr`.
    fn reader(&self) -> TokenStream {
        match self {
            Fun::Path(f) => f.clone(),
            Fun::Expr(e) => quote!(|x, __d| #e),
        }
    }

    /// A JSON reader applied to `arg`, with `__d` in scope.
    fn read(&self, arg: TokenStream) -> TokenStream {
        match self {
            Fun::Path(f) => quote!(#f(#arg, __d)),
            Fun::Expr(e) => quote!({ let x = #arg; #e }),
        }
    }
}

/// A Rust type, how to decode it from `x: &Value` and encode `x: &T`, and
/// how to read it from `x: &Json` and write `x: &T` as schema-based JSON. Encoding
/// and writing also take `__e: ::haus::Encoder`, and reading JSON
/// `__d: ::haus::Decoder`, which count the depth.
struct Rs {
    ty: TokenStream,
    de: Fun,
    en: Fun,
    from_json: Fun,
    to_json: Fun,
    /// `ty` with every codec's target replaced by its base type: a type that
    /// implements `FromJson` and `ToJson`, and says whether the JSON can be `null`.
    shadow: TokenStream,
}

impl Rs {
    /// A type that implements `Decode`, `Encode`, `FromJson` and `ToJson` itself.
    fn plain(ty: TokenStream) -> Rs {
        Rs::named(ty.clone(), ty)
    }

    /// [`Rs::plain`], with the shadow type given.
    fn named(ty: TokenStream, shadow: TokenStream) -> Rs {
        Rs {
            de: Fun::Path(quote!(<#ty as ::haus::Decode>::decode)),
            en: Fun::Path(quote!(::haus::Encode::encode_with)),
            from_json: Fun::Path(quote!(<#ty as ::haus::FromJson>::from_json_with)),
            to_json: Fun::Path(quote!(::haus::ToJson::to_json_with)),
            ty,
            shadow,
        }
    }

    /// Whether the JSON of this type can be `null`, in an implementation of `bound`.
    fn nullable(&self, bound: &str) -> TokenStream {
        let (shadow, bound) = (&self.shadow, format_ident!("{bound}"));
        quote!(<#shadow as ::haus::#bound>::NULLABLE)
    }

    /// A container with helpers `::haus::de::<helper>`, `::haus::ser::<helper>`
    /// and the same in `::haus::json`.
    fn container(ty: TokenStream, shadow: TokenStream, helper: &str, items: &[&Rs]) -> Rs {
        let helper = format_ident!("{helper}");
        let (de, en): (Vec<_>, Vec<_>) = items.iter().map(|r| (r.de.value(), r.en.encoder())).unzip();
        let (from, to): (Vec<_>, Vec<_>) = items.iter().map(|r| (r.from_json.reader(), r.to_json.encoder())).unzip();
        Rs {
            ty,
            de: Fun::Expr(quote!(::haus::de::#helper(x, #(#de),*))),
            en: Fun::Expr(quote!(::haus::ser::#helper(x, __e, #(#en),*))),
            from_json: Fun::Expr(quote!(::haus::json::de::#helper(x, __d, #(#from),*))),
            to_json: Fun::Expr(quote!(::haus::json::ser::#helper(x, __e, #(#to),*))),
            shadow,
        }
    }

    fn boxed(self) -> Rs {
        let (ty, shadow, de, from) = (self.ty, self.shadow, self.de.call(quote!(x)), self.from_json.read(quote!(x)));
        Rs {
            ty: quote!(::std::boxed::Box<#ty>),
            de: Fun::Expr(quote!(#de.map(::std::boxed::Box::new))),
            en: Fun::Expr(self.en.encode(quote!(&**x))),
            from_json: Fun::Expr(quote!(#from.map(::std::boxed::Box::new))),
            to_json: Fun::Expr(self.to_json.encode(quote!(&**x))),
            shadow: quote!(::std::boxed::Box<#shadow>),
        }
    }
}

/// A field of a struct or a struct-like variant.
struct FieldRs {
    name: Ident,
    key: String,
    optional: bool,
    rs: Rs,
    /// `#[deprecated]`, or nothing.
    deprecated: TokenStream,
}

impl FieldRs {
    fn decl(&self, visibility: TokenStream) -> TokenStream {
        let (name, ty, deprecated) = (&self.name, &self.rs.ty, &self.deprecated);
        if self.optional {
            quote!(#deprecated #visibility #name: ::std::option::Option<#ty>)
        } else {
            quote!(#deprecated #visibility #name: #ty)
        }
    }

    /// `name: r.required("key", decode)?`.
    fn de(&self) -> TokenStream {
        self.read(self.rs.de.value())
    }

    /// `name: r.required("key", from_json)?`, `r` being a JSON object.
    fn read_json(&self) -> TokenStream {
        self.read(self.rs.from_json.reader())
    }

    fn read(&self, f: TokenStream) -> TokenStream {
        let (name, key) = (&self.name, &self.key);
        let how = format_ident!("{}", if self.optional { "optional" } else { "required" });
        quote!(#name: r.#how(#key, #f)?)
    }

    /// The entry for `ser::record`: `place` is the field (`self.name`), or a
    /// reference to it when `bound` by a pattern (`name`).
    fn en(&self, place: TokenStream, bound: bool) -> TokenStream {
        self.write(&self.rs.en, place, bound)
    }

    /// The entry for `json::ser::object`, as [`FieldRs::en`].
    fn write_json(&self, place: TokenStream, bound: bool) -> TokenStream {
        self.write(&self.rs.to_json, place, bound)
    }

    fn write(&self, f: &Fun, place: TokenStream, bound: bool) -> TokenStream {
        let key = &self.key;
        if self.optional {
            let f = f.encode_x();
            quote!((#key, #place.as_ref().map(|x| #f)))
        } else {
            let value = f.encode(if bound { place } else { quote!(&#place) });
            quote!((#key, ::std::option::Option::Some(#value)))
        }
    }
}

/// The payload of a case, in Rust.
enum Payload<'a> {
    None,
    Tuple(Vec<Rs>),
    Record { closed: bool, fields: &'a [Field], rs: Vec<FieldRs> },
}

// ── generation ───────────────────────────────────────────────

struct Gen<'a> {
    input: &'a Input<'a>,
    defs: HashMap<&'a str, &'a TypeDef>,
    reach: HashMap<&'a str, HashSet<&'a str>>,
    /// Aliases that refer to themselves (`type Loop = Maybe Loop`): Rust
    /// type aliases can't, so they are newtypes.
    cyclic: HashSet<&'a str>,
    /// The `Maybe`s that always use the tagged form in JSON, by position.
    tagged_maybes: HashSet<usize>,
    codecs: HashMap<&'a str, TokenStream>,
    /// Names of generated types, so names for inline types don't clash.
    names: HashSet<String>,
    items: Vec<TokenStream>,
}

/// Where a type expression is: in which definition, and what an inline type there is called.
#[derive(Clone)]
struct At<'a> {
    owner: &'a TypeDef,
    hint: String,
    /// Behind an array or a map: no `Box` needed.
    contained: bool,
}

impl<'a> At<'a> {
    fn inner(&self, suffix: &str) -> At<'a> {
        At { hint: format!("{}{}", self.hint, pascal(suffix)), ..self.clone() }
    }

    fn contained(&self) -> At<'a> {
        At { contained: true, ..self.clone() }
    }
}

/// A type being defined: its name, generics and documentation.
struct Item<'a> {
    name: Ident,
    params: Vec<Ident>,
    /// Doc comments.
    doc: TokenStream,
    /// Its attributes: `@deprecated` becomes `#[deprecated]`.
    attrs: &'a [Attribute],
    at: At<'a>,
}

impl Item<'_> {
    /// `<A, B>`.
    fn generics(&self) -> TokenStream {
        let params = &self.params;
        if params.is_empty() { quote!() } else { quote!(<#(#params),*>) }
    }

    /// `<A: ::haus::<bound>, …>`.
    fn bounded(&self, bound: &str) -> TokenStream {
        let (params, bound) = (&self.params, format_ident!("{bound}"));
        if params.is_empty() { quote!() } else { quote!(<#(#params: ::haus::#bound),*>) }
    }

    /// Doc comments and `#[deprecated]`, if the item or `also` (the
    /// attributes of the only tag of `closed < Tag … >`) say so: Rust allows
    /// one `#[deprecated]`.
    fn header(&self, also: &[Attribute]) -> TokenStream {
        let (doc, deprecated) = (&self.doc, deprecated([self.attrs, also]));
        quote!(#doc #deprecated)
    }

    /// The type definition, after `header`, its `Decode` and `Encode`
    /// implementations, and its `FromJson` and `ToJson` ones (`json`).
    fn implement(
        &self,
        header: TokenStream,
        definition: TokenStream,
        decode: TokenStream,
        encode: TokenStream,
        json: Json,
    ) -> TokenStream {
        let (name, g) = (&self.name, self.generics());
        let (de_g, en_g) = (self.bounded("Decode"), self.bounded("Encode"));
        let (from_g, to_g) = (self.bounded("FromJson"), self.bounded("ToJson"));
        let Json { from, to, nullable } = json;
        let (from_null, to_null) = match nullable {
            Some((from, to)) => (quote!(const NULLABLE: bool = #from;), quote!(const NULLABLE: bool = #to;)),
            None => (quote!(), quote!()),
        };
        quote! {
            #header
            #[derive(Debug, Clone, PartialEq)]
            #[allow(deprecated)]
            #definition

            #[allow(deprecated)]
            impl #de_g ::haus::Decode for #name #g {
                fn decode(v: &::haus::Value) -> ::std::result::Result<Self, ::haus::DecodeError> {
                    #decode
                }
            }

            #[allow(deprecated)]
            impl #en_g ::haus::Encode for #name #g {
                fn encode_with(&self, __e: ::haus::Encoder) -> ::std::result::Result<::haus::Value, ::haus::EncodeError> {
                    #encode
                }
            }

            #[allow(deprecated)]
            impl #from_g ::haus::FromJson for #name #g {
                #from_null
                #[allow(unused_variables)]
                fn from_json_with(j: &::haus::Json, __d: ::haus::Decoder) -> ::std::result::Result<Self, ::haus::DecodeError> {
                    #from
                }
            }

            #[allow(deprecated)]
            impl #to_g ::haus::ToJson for #name #g {
                #to_null
                fn to_json_with(&self, __e: ::haus::Encoder) -> ::std::result::Result<::haus::Json, ::haus::EncodeError> {
                    #to
                }
            }
        }
    }
}

/// The bodies of `FromJson::from_json_with` (of `j: &Json` and `__d`) and `ToJson::to_json_with`,
/// and `NULLABLE` in each if it isn't false.
struct Json {
    from: TokenStream,
    to: TokenStream,
    nullable: Option<(TokenStream, TokenStream)>,
}

impl<'a> Gen<'a> {
    fn fail<T>(&self, pos: usize, code: Code, reason: impl Into<String>) -> Result<T, Error> {
        Err(error(self.input.text, pos, code, reason))
    }

    fn define_named(&mut self, def: &'a TypeDef) -> Result<(), Error> {
        // A stream is a file of values, read with `haus::from_str_all`: no type of its own.
        if let Ty::Name { name, args, pos } = &def.ty
            && name == "Stream"
        {
            return match args.as_slice() {
                [Ty::Name { .. }] => Ok(()),
                _ => self.fail(*pos, Code::WrongArity, "Stream takes one named type: type Events = Stream Event"),
            };
        }
        let id = format!("{}#{}", self.input.id, def.name);
        let item = Item {
            name: format_ident!("{}", def.name),
            params: def.params.iter().map(|p| param(p)).collect(),
            doc: docs(def.doc.lines().chain(["", &format!("haus type `{id}`.")]).skip_while(|l| l.is_empty())),
            attrs: &def.attrs,
            at: At { owner: def, hint: def.name.clone(), contained: false },
        };
        self.define(&item, &def.ty, Some(&id))
    }

    /// The item for a type, with its id if it has one.
    fn define(&mut self, item: &Item<'a>, ty: &'a Ty, id: Option<&str>) -> Result<(), Error> {
        let (header, name, g) = (item.header(&[]), &item.name, item.generics());
        let (code, nominal) = match ty {
            Ty::Record { closed, fields, .. } => (self.record(item, *closed, fields)?, true),
            Ty::Variant { closed: false, cases, .. } if cases.is_empty() => {
                (quote! { #header pub type #name #g = ::haus::AnyTag; }, false)
            }
            Ty::Variant { closed: true, cases, .. } if cases.len() == 1 => (self.single(item, &cases[0])?, true),
            Ty::Variant { closed, cases, .. } => (self.variant(item, *closed, cases)?, true),
            ty if id.is_some() && self.cyclic.contains(item.name.to_string().as_str()) => {
                (self.newtype(item, ty)?, true)
            }
            ty => {
                let target = self.lower(ty, &item.at)?.ty;
                (quote! { #header #[allow(deprecated)] pub type #name #g = #target; }, false)
            }
        };
        // Structs and enums carry their id; aliases can't.
        let id = id.filter(|_| nominal).map(|id| {
            quote! {
                #[allow(deprecated)]
                impl #g #name #g {
                    /// The type's id (spec §13.3).
                    #[allow(dead_code)]
                    pub const ID: &'static str = #id;
                }
            }
        });
        self.items.push(quote! { #code #id });
        Ok(())
    }

    /// A Rust type for a type expression.
    fn lower(&mut self, ty: &'a Ty, at: &At<'a>) -> Result<Rs, Error> {
        match ty {
            Ty::Param { name, .. } if at.owner.params.contains(name) => {
                let p = param(name);
                Ok(Rs::plain(quote!(#p)))
            }
            Ty::Param { name, pos } => {
                self.fail(*pos, Code::UnknownParameter, format!("unknown type parameter {name}"))
            }
            Ty::Record { .. } | Ty::Variant { .. } => self.inline(ty, at),
            Ty::Name { name, args, pos } => self.named(name, args, *pos, at),
        }
    }

    fn named(&mut self, name: &str, args: &'a [Ty], pos: usize, at: &At<'a>) -> Result<Rs, Error> {
        let arity = |params: usize| {
            (args.len() != params).then(|| format!("{name} takes {params} argument(s), found {}", args.len()))
        };
        let (id, path, params) = if let Some(def) = self.defs.get(name) {
            let ident = format_ident!("{name}");
            (format!("{}#{name}", self.input.id), quote!(#ident), def.params.len())
        } else if let Some(imp) = self.input.imports.get(name) {
            let path = rust_path(&imp.path).ok_or_else(|| {
                error(self.input.text, pos, Code::UnknownType, format!("{} is not a Rust path", imp.path))
            })?;
            (imp.id.clone(), path, imp.params)
        } else if let Some(&(_, params)) = PRELUDE.iter().find(|(n, _)| *n == name) {
            return match arity(params) {
                Some(reason) => self.fail(pos, Code::WrongArity, reason),
                None => self.prelude(name, args, pos, at),
            };
        } else {
            return self.fail(pos, Code::UnknownType, unknown_type(name));
        };
        if let Some(reason) = arity(params) {
            return self.fail(pos, Code::WrongArity, reason);
        }
        if let Some(codec) = self.codecs.get(id.as_str()).filter(|_| args.is_empty()) {
            return Ok(Rs {
                ty: quote!(<#codec as ::haus::Codec>::Target),
                de: Fun::Path(quote!(::haus::de::codec::<#codec>)),
                en: Fun::Path(quote!(::haus::ser::codec::<#codec>)),
                from_json: Fun::Path(quote!(::haus::json::de::codec::<#codec>)),
                to_json: Fun::Path(quote!(::haus::json::ser::codec::<#codec>)),
                shadow: quote!(<#codec as ::haus::Codec>::Base),
            });
        }
        let args = args.iter().map(|a| self.lower(a, at)).collect::<Result<Vec<_>, _>>()?;
        let (tys, shadows) = (args.iter().map(|r| &r.ty), args.iter().map(|r| &r.shadow));
        let rs = match args.is_empty() {
            true => Rs::plain(path),
            false => Rs::named(quote!(#path<#(#tys),*>), quote!(#path<#(#shadows),*>)),
        };
        let recursive = self.reach.get(name).is_some_and(|r| r.contains(at.owner.name.as_str()));
        Ok(if recursive && !at.contained { rs.boxed() } else { rs })
    }

    fn prelude(&mut self, name: &str, args: &'a [Ty], pos: usize, at: &At<'a>) -> Result<Rs, Error> {
        let scalar = |ty: TokenStream| Ok(Rs::plain(ty));
        match name {
            "Bool" => scalar(quote!(bool)),
            "String" => scalar(quote!(::std::string::String)),
            "Bytes" => scalar(quote!(::haus::Bytes)),
            "Int" => scalar(quote!(::haus::Int)),
            "Decimal" => scalar(quote!(::haus::Decimal)),
            "Int8" | "Int16" | "Int32" | "Int64" => scalar(format_ident!("i{}", &name[3..]).into_token_stream()),
            "UInt8" | "UInt16" | "UInt32" | "UInt64" => scalar(format_ident!("u{}", &name[4..]).into_token_stream()),
            "Float32" | "Float64" => scalar(format_ident!("f{}", &name[5..]).into_token_stream()),
            "Any" => scalar(quote!(::haus::Value)),
            "Secret" => {
                let inner = self.lower(&args[0], at)?;
                let (ty, shadow, de, en) = (&inner.ty, &inner.shadow, inner.de.value(), inner.en.encoder());
                let (from, to) = (inner.from_json.reader(), inner.to_json.encoder());
                let what = format!("Secret {}", args[0]);
                Ok(Rs {
                    ty: quote!(::haus::Secret<#ty>),
                    de: Fun::Expr(quote!(::haus::de::secret(x, #what, #de))),
                    en: Fun::Expr(quote!(::haus::ser::secret(x, __e, #what, #en))),
                    from_json: Fun::Expr(quote!(::haus::json::de::secret(x, __d, #what, #from))),
                    to_json: Fun::Expr(quote!(::haus::json::ser::secret(x, __e, #what, #to))),
                    shadow: quote!(::haus::Secret<#shadow>),
                })
            }
            "Array" => {
                let item = self.lower(&args[0], &at.inner("Item").contained())?;
                let (ty, shadow) = (&item.ty, &item.shadow);
                Ok(Rs::container(quote!(::std::vec::Vec<#ty>), quote!(::std::vec::Vec<#shadow>), "array", &[&item]))
            }
            "Map" => {
                let value = self.lower(&args[0], &at.inner("Value").contained())?;
                let (ty, shadow) = (&value.ty, &value.shadow);
                Ok(Rs::container(
                    quote!(::std::collections::BTreeMap<::std::string::String, #ty>),
                    quote!(::std::collections::BTreeMap<::std::string::String, #shadow>),
                    "map",
                    &[&value],
                ))
            }
            "Maybe" => {
                let some = self.lower(&args[0], at)?;
                let (ty, shadow) = (&some.ty, &some.shadow);
                let (from, to) = (some.from_json.reader(), some.to_json.encoder());
                // `true` forces the tagged form, as for an inner type whose JSON can be null.
                let (from_null, to_null) = match self.tagged_maybes.contains(&pos) {
                    true => (quote!(true), quote!(true)),
                    false => (some.nullable("FromJson"), some.nullable("ToJson")),
                };
                Ok(Rs {
                    from_json: Fun::Expr(quote!(::haus::json::de::maybe(x, __d, #from_null, #from))),
                    to_json: Fun::Expr(quote!(::haus::json::ser::maybe(x, __e, #to_null, #to))),
                    ..Rs::container(
                        quote!(::std::option::Option<#ty>),
                        quote!(::std::option::Option<#shadow>),
                        "maybe",
                        &[&some],
                    )
                })
            }
            "Result" => {
                let (err, ok) = (self.lower(&args[0], &at.inner("Err"))?, self.lower(&args[1], &at.inner("Ok"))?);
                let (e, a, e_shadow, a_shadow) = (&err.ty, &ok.ty, &err.shadow, &ok.shadow);
                Ok(Rs::container(
                    quote!(::std::result::Result<#a, #e>),
                    quote!(::std::result::Result<#a_shadow, #e_shadow>),
                    "result",
                    &[&ok, &err],
                ))
            }
            _ => self.fail(
                pos,
                Code::MisplacedStream,
                format!("{name} is only allowed as the whole type of a definition"),
            ),
        }
    }

    /// A record or variant written inline: a type of its own, named after where it is.
    fn inline(&mut self, ty: &'a Ty, at: &At<'a>) -> Result<Rs, Error> {
        let name = at.hint.clone();
        if !self.names.insert(name.clone()) {
            return self.fail(
                ty.pos(),
                Code::DuplicateType,
                format!("the inline type here would be called {name}, which is taken; give it a name"),
            );
        }
        let mut used = HashSet::new();
        params_in(ty, &mut used);
        let item = Item {
            name: format_ident!("{name}"),
            params: at.owner.params.iter().filter(|p| used.contains(p.as_str())).map(|p| param(p)).collect(),
            doc: docs([format!("`{name}`, inline in {}.", at.owner.name).as_str()].into_iter()),
            attrs: &[],
            at: At { hint: name, ..at.clone() },
        };
        self.define(&item, ty, None)?;
        let (ident, g) = (&item.name, item.generics());
        Ok(Rs::plain(quote!(#ident #g)))
    }

    fn fields(&mut self, fields: &'a [Field], at: &At<'a>) -> Result<Vec<FieldRs>, Error> {
        let out = fields
            .iter()
            .map(|f| {
                let rs = self.lower(&f.ty, &at.inner(&f.key))?;
                Ok(FieldRs {
                    name: field_ident(&f.key),
                    key: f.key.clone(),
                    optional: f.optional,
                    rs,
                    deprecated: deprecated([f.attrs.as_slice()]),
                })
            })
            .collect::<Result<Vec<_>, Error>>()?;
        match out.iter().enumerate().find(|(i, f)| out[..*i].iter().any(|g| g.name == f.name)) {
            Some((i, f)) => self.fail(
                fields[i].pos,
                Code::DuplicateField,
                format!("fields {} and another one are both {} in Rust", f.key, f.name),
            ),
            None => Ok(out),
        }
    }

    fn payload(&mut self, case: &'a Case, at: &At<'a>) -> Result<Payload<'a>, Error> {
        let at = at.inner(&case.tag);
        Ok(match case.payload.as_slice() {
            [] => Payload::None,
            [Ty::Record { closed, fields, .. }] => {
                Payload::Record { closed: *closed, fields, rs: self.fields(fields, &at)? }
            }
            [one] => Payload::Tuple(vec![self.lower(one, &at)?]),
            items => Payload::Tuple(
                items
                    .iter()
                    .enumerate()
                    .map(|(i, t)| self.lower(t, &at.inner(&i.to_string())))
                    .collect::<Result<_, _>>()?,
            ),
        })
    }

    /// `{ … }`: a struct.
    fn record(&mut self, item: &Item<'a>, closed: bool, fields: &'a [Field]) -> Result<TokenStream, Error> {
        let fs = self.fields(fields, &item.at)?;
        let (name, g, label) = (&item.name, item.generics(), item.name.to_string());
        let decls = fs.iter().map(|f| f.decl(quote!(pub)));
        let decoded = fs.iter().map(FieldRs::de);
        let entries = fs.iter().map(|f| {
            let n = &f.name;
            f.en(quote!(self.#n), false)
        });
        let bind = bind_record(quote!(::haus::de::Record::new(v, #label)), closed, fields);
        let json_bind = bind_record(quote!(::haus::json::de::Object::new(j, __d, #label)), closed, fields);
        let read = fs.iter().map(FieldRs::read_json);
        let written = fs.iter().map(|f| {
            let n = &f.name;
            f.write_json(quote!(self.#n), false)
        });
        Ok(item.implement(
            item.header(&[]),
            quote!(pub struct #name #g { #(#decls),* }),
            quote! {
                #bind
                ::std::result::Result::Ok(Self { #(#decoded),* })
            },
            quote!(::haus::ser::record(__e, |__e| [#(#entries),*])),
            Json {
                nullable: None,
                from: quote! {
                    #json_bind
                    ::std::result::Result::Ok(Self { #(#read),* })
                },
                to: quote!(::haus::json::ser::object(__e, |__e| [#(#written),*])),
            },
        ))
    }

    /// An alias that refers to itself: a struct around the aliased type.
    fn newtype(&mut self, item: &Item<'a>, ty: &'a Ty) -> Result<TokenStream, Error> {
        let inner = self.lower(ty, &item.at)?;
        let (name, g, inner_ty) = (&item.name, item.generics(), &inner.ty);
        // Its JSON can be null only through a `Maybe` that doesn't reach itself.
        let mut body = ty;
        while let Ty::Name { name, args, .. } = body
            && name == "Secret"
        {
            body = &args[0];
        }
        let nullable = match body {
            Ty::Name { name, pos, .. } if name == "Maybe" && self.tagged_maybes.contains(pos) => None,
            _ => Some((inner.nullable("FromJson"), inner.nullable("ToJson"))),
        };
        Ok(item.implement(
            item.header(&[]),
            quote!(pub struct #name #g (pub #inner_ty);),
            {
                let de = inner.de.call(quote!(v));
                quote!(#de.map(Self))
            },
            inner.en.encode(quote!(&self.0)),
            Json {
                from: {
                    let from = inner.from_json.read(quote!(j));
                    quote!(#from.map(Self))
                },
                to: inner.to_json.encode(quote!(&self.0)),
                nullable,
            },
        ))
    }

    /// `closed < Tag … >`: a struct, checked for its tag.
    fn single(&mut self, item: &Item<'a>, case: &'a Case) -> Result<TokenStream, Error> {
        let (name, g, label, tag) = (&item.name, item.generics(), item.name.to_string(), &case.tag);
        // Checks the tag a JSON object or string holds.
        let check = quote! {
            if tag != #tag {
                return ::std::result::Result::Err(::haus::de::unknown_tag(tag, &[#tag]));
            }
        };
        let tagged = quote!(let (tag, r) = ::haus::json::de::variant(j, __d, #label)?; #check);
        let (definition, decode, encode, json) = match self.payload(case, &item.at)? {
            Payload::None => (
                quote!(pub struct #name;),
                quote! {
                    ::haus::de::args::<0>(tag, args)?;
                    ::std::result::Result::Ok(Self)
                },
                quote!(__e.tag(#tag)),
                // A closed variant whose tags have no payload: a string.
                Json {
                    nullable: None,
                    from: quote! {
                        let tag = ::haus::json::de::tag_name(j, #label)?;
                        #check
                        ::std::result::Result::Ok(Self)
                    },
                    to: quote!(::haus::json::ser::tag_name(#tag)),
                },
            ),
            Payload::Tuple(items) => {
                let tys = items.iter().map(|r| &r.ty);
                let (bind, values) = tuple_de(&items, &case.payload);
                let (json_bind, read) = tuple_from_json(&items);
                let vars = vars(items.len());
                let encoded = tuple_en(&items);
                let written = tuple_to_json(&items);
                (
                    quote!(pub struct #name #g (#(pub #tys),*);),
                    quote! { #bind ::std::result::Result::Ok(Self(#(#values),*)) },
                    quote! {
                        let Self(#(#vars),*) = self;
                        ::haus::ser::tagged(#tag, __e, |__e| [#(#encoded),*])
                    },
                    Json {
                        nullable: None,
                        from: quote! { #tagged #json_bind ::std::result::Result::Ok(Self(#(#read),*)) },
                        to: quote! {
                            let Self(#(#vars),*) = self;
                            ::haus::json::ser::tagged(#tag, __e, |__e| [#(#written),*])
                        },
                    },
                )
            }
            Payload::Record { closed, fields, rs } => {
                let decls = rs.iter().map(|f| f.decl(quote!(pub)));
                let decoded = rs.iter().map(FieldRs::de);
                let entries = rs.iter().map(|f| {
                    let n = &f.name;
                    f.en(quote!(self.#n), false)
                });
                let bind = bind_record(record_payload(fields), closed, fields);
                let json = if let Some(field) = reserved_field(fields) {
                    Json {
                        nullable: None,
                        from: quote! { #tagged ::std::result::Result::Err(::haus::json::de::no_json_form(#tag, #field)) },
                        to: quote!(::haus::json::ser::no_json_form(#tag, #field)),
                    }
                } else {
                    let read = rs.iter().map(FieldRs::read_json);
                    let written = rs.iter().map(|f| {
                        let n = &f.name;
                        f.write_json(quote!(self.#n), false)
                    });
                    let json_bind = bind_payload(closed, fields);
                    Json {
                        nullable: None,
                        from: quote! { #tagged #json_bind ::std::result::Result::Ok(Self { #(#read),* }) },
                        to: quote!(::haus::json::ser::tagged_object(#tag, __e, |__e| [#(#written),*])),
                    }
                };
                (
                    quote!(pub struct #name #g { #(#decls),* }),
                    quote! {
                        #bind
                        ::std::result::Result::Ok(Self { #(#decoded),* })
                    },
                    quote!(::haus::ser::tagged_record(#tag, __e, |__e| [#(#entries),*])),
                    json,
                )
            }
        };
        Ok(item.implement(
            item.header(&case.attrs),
            definition,
            quote! {
                let (tag, args) = ::haus::de::variant(v, #label)?;
                if tag != #tag {
                    return ::std::result::Result::Err(::haus::de::unknown_tag(tag, &[#tag]));
                }
                #decode
            },
            encode,
            json,
        ))
    }

    /// `< A | B T | C { … } >`: an enum, with `Unknown` for other tags if it's open.
    fn variant(&mut self, item: &Item<'a>, closed: bool, cases: &'a [Case]) -> Result<TokenStream, Error> {
        if let Some(case) = cases.iter().find(|c| !closed && c.tag == "Unknown") {
            return self.fail(
                case.pos,
                Code::DuplicateTag,
                "an open variant can't have a tag Unknown in Rust (unknown tags decode to Unknown); close it",
            );
        }
        let (name, g, label) = (&item.name, item.generics(), item.name.to_string());
        // A closed variant whose tags have no payload is a string in JSON.
        let names_only = closed && cases.iter().all(|c| c.payload.is_empty());
        let arms = cases
            .iter()
            .map(|case| {
                let (tag, v) = (&case.tag, format_ident!("{}", case.tag));
                let deprecated = deprecated([case.attrs.as_slice()]);
                Ok(match self.payload(case, &item.at)? {
                    Payload::None => Arm {
                        decl: quote!(#deprecated #v),
                        de: quote!(#tag => { ::haus::de::args::<0>(tag, args)?; ::std::result::Result::Ok(Self::#v) }),
                        en: quote!(Self::#v => __e.tag(#tag)),
                        from_json: match names_only {
                            true => quote!(#tag => ::std::result::Result::Ok(Self::#v),),
                            false => quote!(#tag => { r.args::<0>()?; ::std::result::Result::Ok(Self::#v) }),
                        },
                        to_json: match names_only {
                            true => quote!(Self::#v => ::haus::json::ser::tag_name(#tag)),
                            false => quote!(Self::#v => ::haus::json::ser::tagged(#tag, __e, |_| [])),
                        },
                    },
                    Payload::Tuple(items) => {
                        let tys = items.iter().map(|r| &r.ty);
                        let (bind, values) = tuple_de(&items, &case.payload);
                        let (json_bind, read) = tuple_from_json(&items);
                        let vars = vars(items.len());
                        let encoded = tuple_en(&items);
                        let written = tuple_to_json(&items);
                        Arm {
                            decl: quote!(#deprecated #v(#(#tys),*)),
                            de: quote!(#tag => { #bind ::std::result::Result::Ok(Self::#v(#(#values),*)) }),
                            en: quote!(Self::#v(#(#vars),*) => ::haus::ser::tagged(#tag, __e, |__e| [#(#encoded),*])),
                            from_json: quote!(#tag => { #json_bind ::std::result::Result::Ok(Self::#v(#(#read),*)) }),
                            to_json: quote!(Self::#v(#(#vars),*) => ::haus::json::ser::tagged(#tag, __e, |__e| [#(#written),*])),
                        }
                    }
                    Payload::Record { closed, fields, rs } => {
                        let decls = rs.iter().map(|f| f.decl(quote!()));
                        let decoded = rs.iter().map(FieldRs::de);
                        let names: Vec<_> = rs.iter().map(|f| &f.name).collect();
                        let entries = rs.iter().map(|f| {
                            let n = &f.name;
                            f.en(quote!(#n), true)
                        });
                        let bind = bind_record(record_payload(fields), closed, fields);
                        let (from_json, to_json) = if let Some(field) = reserved_field(fields) {
                            (
                                quote!(#tag => ::std::result::Result::Err(::haus::json::de::no_json_form(#tag, #field)),),
                                quote!(Self::#v { .. } => ::haus::json::ser::no_json_form(#tag, #field)),
                            )
                        } else {
                            let read = rs.iter().map(FieldRs::read_json);
                            let written = rs.iter().map(|f| {
                                let n = &f.name;
                                f.write_json(quote!(#n), true)
                            });
                            let json_bind = bind_payload(closed, fields);
                            (
                                quote!(#tag => { #json_bind ::std::result::Result::Ok(Self::#v { #(#read),* }) }),
                                quote!(Self::#v { #(#names),* } => ::haus::json::ser::tagged_object(#tag, __e, |__e| [#(#written),*])),
                            )
                        };
                        Arm {
                            decl: quote!(#deprecated #v { #(#decls),* }),
                            de: quote!(#tag => {
                                #bind
                                ::std::result::Result::Ok(Self::#v { #(#decoded),* })
                            }),
                            en: quote!(Self::#v { #(#names),* } => ::haus::ser::tagged_record(#tag, __e, |__e| [#(#entries),*])),
                            from_json,
                            to_json,
                        }
                    }
                })
            })
            .collect::<Result<Vec<_>, Error>>()?;
        let decls = arms.iter().map(|a| &a.decl);
        let (decode, encode) = (arms.iter().map(|a| &a.de), arms.iter().map(|a| &a.en));
        let (from_json, to_json) = (arms.iter().map(|a| &a.from_json), arms.iter().map(|a| &a.to_json));
        let tags = cases.iter().map(|c| &c.tag);
        let unknown_tag = quote!(::haus::de::unknown_tag(tag, &[#(#tags),*]));
        let (other_decl, other_de, other_en, other_from_json, other_to_json) = if closed {
            let at_tag = if names_only { quote!() } else { quote!(.field("_tag")) };
            (
                quote!(),
                quote!(_ => ::std::result::Result::Err(#unknown_tag)),
                quote!(),
                quote!(_ => ::std::result::Result::Err(#unknown_tag #at_tag)),
                quote!(),
            )
        } else {
            (
                quote! {
                    /// A tag this schema doesn't list, kept as it was.
                    Unknown(::haus::Unknown),
                },
                quote!(_ => ::std::result::Result::Ok(Self::Unknown(::haus::Unknown::new(tag, args)))),
                quote!(Self::Unknown(u) => ::haus::Encode::encode_with(u, __e),),
                quote!(_ => ::std::result::Result::Ok(Self::Unknown(r.unknown(tag)?))),
                quote!(Self::Unknown(u) => ::haus::json::ser::unknown(u, __e),),
            )
        };
        let read_tag = match names_only {
            true => quote!(let tag = ::haus::json::de::tag_name(j, #label)?;),
            false => quote!(let (tag, r) = ::haus::json::de::variant(j, __d, #label)?;),
        };
        Ok(item.implement(
            item.header(&[]),
            quote!(pub enum #name #g { #(#decls,)* #other_decl }),
            quote! {
                let (tag, args) = ::haus::de::variant(v, #label)?;
                match tag {
                    #(#decode)*
                    #other_de
                }
            },
            quote! {
                match self {
                    #(#encode,)*
                    #other_en
                }
            },
            Json {
                nullable: None,
                from: quote! {
                    #read_tag
                    match tag {
                        #(#from_json)*
                        #other_from_json
                    }
                },
                to: quote! {
                    match self {
                        #(#to_json,)*
                        #other_to_json
                    }
                },
            },
        ))
    }
}

/// A case of an enum: its declaration, and its arms in `decode`, `encode`,
/// `from_json` and `to_json`.
struct Arm {
    decl: TokenStream,
    de: TokenStream,
    en: TokenStream,
    from_json: TokenStream,
    to_json: TokenStream,
}

// ── helpers ──────────────────────────────────────────────────

/// `a0, a1, …`: the payload values, bound by a pattern.
fn vars(n: usize) -> Vec<Ident> {
    (0..n).map(|i| format_ident!("a{i}")).collect()
}

/// `let [a0, a1] = typed_args::<2>(tag, args, &["Float64", "Float64"])?;`
/// and the decoded values; `types` are the case's, which the hint names.
fn tuple_de(items: &[Rs], types: &[Ty]) -> (TokenStream, Vec<TokenStream>) {
    let (vars, n) = (vars(items.len()), Literal::usize_unsuffixed(items.len()));
    let types = types.iter().map(|t| t.to_string());
    let bind = quote!(let [#(#vars),*] = ::haus::de::typed_args::<#n>(tag, args, &[#(#types),*])?;);
    let values = items
        .iter()
        .zip(&vars)
        .enumerate()
        .map(|(i, (r, var))| {
            let (i, f) = (Literal::usize_unsuffixed(i), r.de.value());
            quote!(::haus::de::arg(tag, #i, #var, #f)?)
        })
        .collect();
    (bind, values)
}

/// `record_payload(tag, args, "{ r: Float64 }")`: the record payload of a
/// case, with its type as the schema writes it for the hint.
fn record_payload(fields: &[Field]) -> TokenStream {
    let shown: Vec<String> = fields
        .iter()
        .take(6)
        .map(|f| {
            let word = f.key.chars().next().is_some_and(|c| c.is_ascii_lowercase() || c == '_')
                && f.key.chars().all(|c| c.is_ascii_alphanumeric() || c == '_');
            let key = if word { f.key.clone() } else { format!("{:?}", f.key) };
            format!("{key}{}: {}", if f.optional { "?" } else { "" }, f.ty)
        })
        .collect();
    let more = if fields.len() > 6 { ", …" } else { "" };
    let record = match shown.is_empty() {
        true => "{}".to_owned(),
        false => format!("{{ {}{more} }}", shown.join(", ")),
    };
    quote!(::haus::de::record_payload(tag, args, #record))
}

/// The encoded payload values `a0`, `a1`, ….
fn tuple_en(items: &[Rs]) -> Vec<TokenStream> {
    items.iter().zip(vars(items.len())).map(|(r, var)| r.en.encode(quote!(#var))).collect()
}

/// `let [a0, a1] = r.args::<2>()?;` (`r` a tag's JSON object), `__d` inside
/// the payload, and the values read.
fn tuple_from_json(items: &[Rs]) -> (TokenStream, Vec<TokenStream>) {
    let (vars, n) = (vars(items.len()), Literal::usize_unsuffixed(items.len()));
    let bind = quote!(let [#(#vars),*] = r.args::<#n>()?; let __d = r.inner()?;);
    let values = items
        .iter()
        .zip(&vars)
        .enumerate()
        .map(|(i, (r, var))| {
            let (i, f) = (Literal::usize_unsuffixed(i), r.from_json.reader());
            quote!(::haus::json::de::arg::<#n, _>(#i, #var, __d, #f)?)
        })
        .collect();
    (bind, values)
}

/// The payload values `a0`, `a1`, … as JSON.
fn tuple_to_json(items: &[Rs]) -> Vec<TokenStream> {
    items.iter().zip(vars(items.len())).map(|(r, var)| r.to_json.encode(quote!(#var))).collect()
}

/// The first field of a record payload named `_tag` or `_args`: the case
/// has no schema-based JSON form (spec §16.3).
fn reserved_field(fields: &[Field]) -> Option<&str> {
    fields.iter().map(|f| f.key.as_str()).find(|k| matches!(*k, "_tag" | "_args"))
}

/// `r.closed(&["_tag", "a"])?;` for a closed record payload in JSON (`r` the tag's object).
fn bind_payload(closed: bool, fields: &[Field]) -> TokenStream {
    let keys = fields.iter().map(|f| &f.key);
    match closed {
        true => quote! { r.closed(&[#(#keys),*])?; },
        false => quote!(),
    }
}

/// `let r = <record>?;`, then `r.closed(&["a", "b"])?;` for a closed record.
/// An open record without fields only has to be a record: `<record>?;`.
fn bind_record(record: TokenStream, closed: bool, fields: &[Field]) -> TokenStream {
    let keys = fields.iter().map(|f| &f.key);
    match (closed, fields.is_empty()) {
        (true, _) => quote! { let r = #record?; r.closed(&[#(#keys),*])?; },
        (false, true) => quote! { #record?; },
        (false, false) => quote! { let r = #record?; },
    }
}

/// `///` lines.
fn docs<'s>(lines: impl Iterator<Item = &'s str>) -> TokenStream {
    let lines = lines.map(|l| if l.is_empty() { String::new() } else { format!(" {l}") });
    quote!(#(#[doc = #lines])*)
}

/// `#[deprecated(note = "…")]` if any of the attribute lists say so (spec
/// §14), or nothing. Their messages are joined: Rust allows one `#[deprecated]`.
fn deprecated<'a>(lists: impl IntoIterator<Item = &'a [Attribute]>) -> TokenStream {
    let deprecations: Vec<Option<&str>> = lists.into_iter().filter_map(deprecation).collect();
    if deprecations.is_empty() {
        return quote!();
    }
    let mut notes: Vec<&str> = deprecations.into_iter().flatten().collect();
    notes.dedup();
    match notes.join("; ") {
        note if note.is_empty() => quote!(#[deprecated]),
        note => quote!(#[deprecated(note = #note)]),
    }
}

/// The parameters a type expression uses.
fn params_in<'a>(ty: &'a Ty, out: &mut HashSet<&'a str>) {
    match ty {
        Ty::Param { name, .. } => {
            out.insert(name);
        }
        Ty::Name { args, .. } => args.iter().for_each(|a| params_in(a, out)),
        Ty::Record { fields, .. } => fields.iter().for_each(|f| params_in(&f.ty, out)),
        Ty::Variant { cases, .. } => cases.iter().flat_map(|c| &c.payload).for_each(|t| params_in(t, out)),
    }
}

/// A type parameter: `a` → `A`, `elem` → `Elem`.
fn param(p: &str) -> Ident {
    format_ident!("{}", pascal(p))
}

/// `deliverTo` → `DeliverTo`, `pt-BR` → `PtBr`.
fn pascal(s: &str) -> String {
    s.split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|w| !w.is_empty())
        .map(|w| w[..1].to_ascii_uppercase() + &w[1..])
        .collect()
}

/// Keywords a field can't be called (`r#type` instead).
const KEYWORDS: &[&str] = &[
    "as", "async", "await", "break", "const", "continue", "dyn", "else", "enum", "extern", "false", "fn", "for", "gen",
    "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return", "static", "struct",
    "trait", "true", "type", "unsafe", "use", "where", "while", "abstract", "become", "box", "do", "final", "macro",
    "override", "priv", "try", "typeof", "unsized", "virtual", "yield",
];

/// A field name in Rust: `deliverTo` → `deliver_to`, `type` → `r#type`, `pt-BR` → `pt_br`.
fn field_ident(key: &str) -> Ident {
    let snake = key.chars().enumerate().fold(String::new(), |mut out, (i, c)| {
        match c {
            c if c.is_ascii_uppercase() => {
                if i > 0 && !out.ends_with('_') {
                    out.push('_');
                }
                out.push(c.to_ascii_lowercase());
            }
            c if c.is_ascii_alphanumeric() || c == '_' => out.push(c),
            _ if !out.ends_with('_') => out.push('_'),
            _ => {}
        }
        out
    });
    match snake.as_str() {
        "" => format_ident!("_field"),
        // These can't be raw identifiers.
        "self" | "super" | "crate" => format_ident!("{snake}_"),
        s if s.starts_with(|c: char| c.is_ascii_digit()) => format_ident!("_{s}"),
        s if KEYWORDS.contains(&s) => Ident::new_raw(s, Span::call_site()),
        s => format_ident!("{s}"),
    }
}
